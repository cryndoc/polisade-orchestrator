#: Журнал гейта — его собственная память о том, ЧТО он спрашивал и в каком
#: состоянии был предмет вопроса на тот момент. Лежит в `.state/`, куда
#: `.gitignore` проекта не пускает git: это не состояние проекта и не решение
#: PM, а рабочая запись инструмента, и коммитить её нечего.
LEDGER_REL = ".state/pm-gate-ledger.json"
LEDGER_VERSION = 1

#: Адрес, по которому предмет вопроса опознаётся МЕЖДУ прогонами. Не ключ:
#: ключ меняется вместе с любым машинным полем вопроса, и статус, сменившийся
#: с одного неизвестного значения на другое, дал бы «вопрос закрыт» там, где
#: он всего лишь переформулирован.
def question_address(item) -> tuple:
    kind = str(item.get("kind") or "")
    ident = str(item.get("id") or "")
    if ident:
        return (kind, "id", ident)
    return (kind, "path", str(item.get("path") or ""))


def _digest_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


#: Предмета НЕТ — и это отдельное поле слепка, а не особое значение внутри
#: хеша: «удалённый артефакт» и «файл, содержимое которого случайно совпало с
#: нашей меткой отсутствия» это разные вещи, а один digest на оба делал бы
#: инвариант «удаление отличимо» неправдой (ревьюер, круг 1).
def _absent_subject(source, error=None):
    """Предмета нет. `error` отличает «нет файла» от «файл есть, не читается».

    Это РАЗНЫЕ исходы, и склеивать их нельзя: исчезновение снимает запись с
    учёта, а отказ в правах — временная слепота, при которой запись обязана
    остаться. Иначе `chmod 000` на минуту стирал бы память барьера
    (ревьюер, круг 2).
    """
    out = {"tracked": True, "present": False, "source": source, "digest": None}
    if error is not None and not isinstance(error, FileNotFoundError) \
            and not isinstance(error, NotADirectoryError) \
            and not isinstance(error, IsADirectoryError):
        out["unreadable"] = True
        out["detail"] = ("предмет не прочитан (%s)" % error.__class__.__name__)
    return out


#: Версия дерева, к которой привязан слепок. Журнал локальный, а рабочая
#: копия переключается: на ветке A вопрос задан, на ветке B тот же артефакт
#: давно решён и вопроса нет — сравнение слепка A с диском B дало бы отказ
#: там, где в этом цикле никто ничего за PM не решал (оба ревьюера, круг 1).
#: Читается ФАЙЛ `.git/HEAD`, а не `git` из PATH: инструмент не имеет права
#: зависеть от внешнего процесса ради вспомогательной записи, а проект вообще
#: может не быть репозиторием — тогда версия пуста и сравнение идёт как
#: раньше.
#:
#: Это идентичность ВЕТКИ, а не коммита, и выбор сознательный (ревьюер, круг
#: 2, предложивший разрешать ref до sha). Привязка к sha выключала бы барьер
#: после ЛЮБОГО коммита между двумя прогонами — а коммит между прогонами это
#: штатный ход рецепта, то есть обычная работа делала бы гейт слепым. Что при
#: этом не ловится, названо прямо: `git reset --hard` на другой коммит ТОЙ ЖЕ
#: ветки строку `HEAD` не меняет, и решение, приехавшее из истории, будет
#: предъявлено как непризнанная правка — это лишний отказ ценой одной
#: команды, а не пропуск.
#: Версия дерева для detached-контура. Одно значение на все коммиты: сменить
#: коммит — не решение PM, а штатный ход рецепта.
DETACHED_TREE = "detached"


def tree_version(root) -> str:
    try:
        git = os.path.join(os.path.realpath(str(root)), ".git")
        if os.path.isfile(git):
            with open(git, encoding="utf-8", errors="replace") as handle:
                line = handle.read().strip()
            if not line.startswith("gitdir:"):
                return ""
            git = line[len("gitdir:"):].strip()
            if not os.path.isabs(git):
                git = os.path.join(os.path.realpath(str(root)), git)
        with open(os.path.join(git, "HEAD"), encoding="utf-8",
                  errors="replace") as handle:
            head = one_line(handle.read().strip())
        if head.startswith("ref:"):
            return head
        # DETACHED HEAD: в файле лежит sha коммита, и вернуть его значило бы
        # сделать ровно то, что абзац выше объявляет недопустимым — привязать
        # барьер к коммиту. Замерено: один и тот же сценарий «вопрос → правка
        # предмета → коммит → повтор» на ветке даёт отказ (rc=3), а в detached
        # — зелёный выход (rc=0), потому что запись с прошлым sha перестаёт
        # судиться. Detached — не экзотика: так работают worktree, CI и
        # харнессы, а инвариант #10 прямо называет это штатным режимом скиллов.
        # Значение ПОСТОЯННОЕ, а не хеш пути. Первая редакция брала sha256 от
        # realpath каталога gitdir — и заводила тихую дыру взамен закрытой:
        # `mv` проекта менял хеш, и ВСЕ записи переставали судиться, то есть
        # ответ за PM, сделанный до переноса, не предъявлялся никогда.
        # Различать контуры здесь не нужно ПО ПОСТРОЕНИЮ: журнал лежит внутри
        # рабочего дерева (`.state/pm-gate-ledger.json`), и у соседнего дерева
        # он свой — записи изолированы местом файла, а не значением поля. Поле
        # различает переключения ВНУТРИ одного дерева, а в detached
        # переключать нечего.
        return DETACHED_TREE
    except (OSError, ValueError):
        return ""


def _safe_target(root, rel):
    """Путь внутри проекта, либо None. Никогда не бросает."""
    if not rel:
        return None
    try:
        base = os.path.realpath(str(root))
        target = os.path.realpath(os.path.join(base, str(rel)))
    except (OSError, ValueError):
        return None
    if target != base and not target.startswith(base + os.sep):
        return None
    return target


def _experimental_flag(item):
    """Имя флага режима, про который спрашивает вопрос, либо None."""
    kind = str(item.get("kind") or "")
    ident = str(item.get("id") or "")
    if kind == "experimental-default-divergence":
        return ident.rsplit(".", 1)[-1] if ident else None
    if kind == "mode-unavailable-on-target":
        return ident or None
    return None


#: Идентификатор вопроса про расходящийся шаблон. Строится там же, где сам
#: вопрос (`polisade_migrate.py`), и читается здесь по одному написанию.
TEMPLATE_NOTE_PREFIX = "docs-template-diverged:"


def _template_name(item):
    ident = str(item.get("id") or "")
    if ident.startswith(TEMPLATE_NOTE_PREFIX):
        return ident[len(TEMPLATE_NOTE_PREFIX):] or None
    return None


def subject_fingerprint(root, state, item) -> dict:
    """Слепок ПРЕДМЕТА вопроса — полей, правка которых его закрывает.

    Читается из вопроса (`kind`/`id`/`path`), а не из его формулировки, и
    поэтому считается и тогда, когда вопрос уже не задаётся: сверять «до» и
    «после» больше не с чего — самого вопроса в следующем прогоне нет.

    `tracked: false` — честный ответ «предмет этого класса машинно не
    выражен», а не тихий пропуск: такие вопросы перечисляются в отчёте
    отдельным списком. `present: false` — предмета сейчас НЕТ (файла нет,
    ключа нет); это тоже не решение и отказом не заканчивается.
    """
    path = item.get("path") or ""
    kind = str(item.get("kind") or "")

    if kind in _STATUS_SUBJECT_KINDS:
        # Ровно два поля, а не байты файла: правка текста артефакта —
        # обычная работа, и слепок по всему файлу превращал бы её в решение.
        target = _safe_target(root, path)
        source = STATUS_SUBJECT_SOURCE
        if target is None:
            return {"tracked": False, "source": source,
                    "detail": "адрес артефакта выходит за корень проекта"}
        try:
            with open(target, encoding="utf-8", errors="replace") as handle:
                text = handle.read()
        except (OSError, ValueError) as exc:
            return _absent_subject(source, exc)
        front = parse_frontmatter(text, strip_comments=True)
        value = json.dumps([front.get("status"), front.get("status_reason")],
                           ensure_ascii=False, sort_keys=True)
        return {"tracked": True, "present": True, "source": source,
                "digest": _digest_text(value)}

    flag = _experimental_flag(item)
    if flag:
        source = "settings.experimental.%s" % flag
        settings = state.get("settings") if isinstance(state, dict) else None
        exp = settings.get("experimental") if isinstance(settings, dict) else None
        if not isinstance(exp, dict) or flag not in exp:
            return _absent_subject(source)
        return {
            "tracked": True, "present": True, "source": source,
            "digest": _digest_text(json.dumps(exp[flag], ensure_ascii=False,
                                              sort_keys=True, default=str)),
        }

    if path:
        target = _safe_target(root, path)
        source = "file-bytes:%s" % path
        if target is None:
            return {"tracked": False, "source": source,
                    "detail": "адрес выходит за корень проекта"}
        try:
            with open(target, "rb") as handle:
                raw = handle.read()
        except (OSError, ValueError) as exc:
            return _absent_subject(source, exc)
        return {"tracked": True, "present": True, "source": source,
                "digest": hashlib.sha256(raw).hexdigest()}

    return {"tracked": False, "source": "—",
            "detail": "у вопроса нет машинно выраженного предмета"}


#: Что именно сторожится — ПРАВИЛАМИ, а не списком классов вопросов.
#:
#: Список классов был неправдой в обе стороны (оба ревьюера, круг 1): вопрос
#: класса `malformed-state-field` БЕЗ пути (`schemaVersion`, `artifactIndex`)
#: предмета не имеет и сторожиться не может, а вопрос НЕназванного класса,
#: у которого путь есть, сторожится. Печатать в отчёте перечень, который
#: обещает не то, что делает код, — хуже, чем не печатать ничего: это
#: объявленная граница, на которую нельзя опереться.
TRACKED_SUBJECT_RULES = (
    "вопрос о статусе артефакта → поля `status` и `status_reason` его "
    "frontmatter",
    "вопрос о флаге режима → значение `settings.experimental.<флаг>`",
    "любой другой вопрос, называющий путь в проекте → байты этого файла",
    "вопрос без пути и без флага (например о поле состояния) НЕ сторожится — "
    "он попадает в `decisions_untracked`",
)


def _values_of(token, name):
    """Значения опции `--name=a,b` или `--name` (без значения → `all`)."""
    if token == name:
        return ("all",)
    if token.startswith(name + "="):
        raw = token[len(name) + 1:]
        return tuple(v.strip() for v in raw.split(",") if v.strip()) or ("all",)
    return ()


def answering_option(item, argv):
    """Опция ЭТОГО прогона, которой вопрос закрыт, либо None.

    Опция целиком видна в командной строке — в том же TUI, где PM
    подтверждает вызов, — поэтому закрытие ею это ВИДИМЫЙ явный акт, а не
    тихая правка. Отказом он не заканчивается, но и тишиной не остаётся:
    отчёт и тело PR называют, какая опция какой вопрос закрыла.

    Сопоставление намеренно широкое: цена ложного ОТКАЗА здесь выше цены
    пропуска, а пропуск тут не тишина — он всё равно печатается строкой.
    """
    tokens = [str(t) for t in (argv or [])]
    flag = _experimental_flag(item)
    if flag:
        for token in tokens:
            if token == "--adopt-v2-defaults":
                return token
            for name in ("--enable", "--disable"):
                values = _values_of(token, name)
                if values and ("all" in values or flag in values):
                    return token
    name = _template_name(item)
    if name:
        for token in tokens:
            values = _values_of(token, "--adopt-templates")
            # ЗНАЧЕНИЕ, а не только имя опции: `--adopt-templates=B` не
            # отвечает на вопрос про шаблон A, и зачесть его значило бы
            # пропустить решение, приписав его чужой опции (ревьюер, круг 1).
            if values and ("all" in values or name in values):
                return token
    return None


_HEX64_RE = re.compile(r"^[0-9a-f]{64}$")


def _valid_entry(entry) -> bool:
    """Запись журнала имеет ту форму, которую пишет этот модуль.

    Журнал — обычный файл, и запись в нём это ВХОД, а не наша память, пока
    форма не проверена. Непроверенная запись работала в обе стороны
    (ревьюер, круг 1): `"tracked": "yes"` — истина для `if`, и отсутствующий
    `digest` сравнивался с настоящим как `None != "…"`, то есть мусор в
    журнале предъявлялся PM как принятое им решение.
    """
    if not isinstance(entry, dict):
        return False
    key = entry.get("key")
    if not isinstance(key, str) or not KEY_RE.match(key.strip()):
        return False
    for field in ("kind", "id", "path", "tree", "status"):
        value = entry.get(field)
        if value is not None and not isinstance(value, str):
            return False
    # Автор — не украшение: от него зависит, рассмотрит ли запись хоть кто-то.
    # Запись без автора не судил бы никто и никогда, а лежала бы она вечно —
    # то есть необязательным оказалось поле, на котором держится вся
    # достижимость логики (ревьюер, круг 2).
    if not isinstance(entry.get("asker"), str) or not entry["asker"].strip():
        return False
    if not _valid_timestamp(entry.get("askedAt")):
        return False
    subject = entry.get("subject")
    if not isinstance(subject, dict):
        return False
    if not isinstance(subject.get("tracked"), bool):
        return False
    if subject.get("tracked"):
        if not isinstance(subject.get("present"), bool):
            return False
        digest = subject.get("digest")
        if subject["present"] and not (isinstance(digest, str)
                                       and _HEX64_RE.match(digest)):
            return False
    for field in ("resolvedDigest", "resolvedRecord"):
        value = entry.get(field)
        if value is not None and not (isinstance(value, str)
                                      and _HEX64_RE.match(value)):
            return False
    return True


def read_ledger(root) -> tuple:
    """`(записи, отвергнутых записей, ошибка чтения)`. Никогда не бросает."""
    target = _safe_target(root, LEDGER_REL)
    if target is None:
        return [], 0, "путь журнала выходит за корень проекта"
    try:
        with open(target, encoding="utf-8") as handle:
            doc = json.load(handle)
    except FileNotFoundError:
        return [], 0, None
    except (OSError, ValueError, RecursionError) as exc:
        # Нечитаемый журнал — НЕ «журнала нет»: разница ровно в том, что
        # кто-то его писал. Барьер на этом прогоне слеп, и это сказано вслух.
        return [], 0, "журнал не прочитан (%s)" % exc.__class__.__name__
    entries = doc.get("entries") if isinstance(doc, dict) else None
    if not isinstance(entries, list):
        return [], 0, "журнал не имеет формы `{entries: [...]}`"
    good = [e for e in entries if _valid_entry(e)]
    return good, len(entries) - len(good), None


def write_ledger(root, entries):
    """Записать журнал. Возвращает текст ошибки либо None.

    Ловится ЛЮБОЕ исключение, а не список знакомых: журнал пишется через
    общий писатель состояния, у которого есть собственный отказ (барьер
    полей гейта срабатывает, если в журнал кто-то положил поле с таким
    именем), и необработанное исключение здесь оставило бы stdout пустым —
    то есть поломало бы контракт «один JSON-документ» ради вспомогательной
    записи (ревьюер, круг 1).
    """
    target = _safe_target(root, LEDGER_REL)
    if target is None:
        return "путь журнала выходит за корень проекта"
    try:
        os.makedirs(os.path.dirname(target), exist_ok=True)
        atomic_write_json(target, {"version": LEDGER_VERSION,
                                   "entries": list(entries)})
    except Exception as exc:                        # noqa: BLE001 — см. выше
        return "журнал не записан (%s)" % exc.__class__.__name__
    return None


def current_asker(argv0=None) -> str:
    """Кто задал вопрос — имя инструмента этого прогона.

    Одно написание на оба носителя: значение выводится из `sys.argv[0]`, а не
    передаётся строкой из каждого вызывающего, потому что два написания
    одного имени разошлись бы молча — и тогда прогон перестал бы узнавать
    собственные записи, то есть барьер выключился бы сам.
    """
    raw = argv0 if argv0 is not None else (sys.argv[0] if sys.argv else "")
    name = os.path.basename(str(raw or ""))
    if name.endswith(".py"):
        name = name[:-3]
    return name or "unknown"


def _entry_item(entry):
    """Поля записи для отчёта. Каждое — ОДНОЙ строкой.

    Всё это пришло из файла, который правит кто угодно, и печатается PM'у на
    терминал и в markdown тела PR: `\\r` в адресе перерисовал бы строку
    поверх напечатанной, перевод строки добавил бы в тело PR пункт, которого
    инструмент не писал (ревьюер, круг 1; тот же класс, что и в #404).
    """
    subject = entry.get("subject") if isinstance(entry.get("subject"), dict) else {}
    return {
        "key": one_line(entry.get("key") or "—"),
        "kind": one_line(entry.get("kind") or "—"),
        "id": one_line(entry.get("id") or ""),
        "path": one_line(entry.get("path") or ""),
        "askedAt": one_line(entry.get("askedAt") or ""),
        "subject": one_line(subject.get("source") or "—"),
    }


def _mark_resolved(entry, digest, record_digest, by):
    """Копия записи с отметкой «здесь предмет назван». Одно место на все."""
    marked = dict(entry)
    marked["resolvedDigest"] = digest
    marked["resolvedBy"] = by
    if record_digest:
        marked["resolvedRecord"] = record_digest
    return marked


def reconcile_decisions(root, state, questions, deferrals, decisions,
                        argv=None, confirm_command=None, asker=None):
    """Сверить предметы закрытых вопросов со слепками из журнала.

    Возвращает поля вердикта: что закрыто опцией прогона, что исчезло, что не
    сторожится, и что закрыто правкой, которую никто не назвал.

    Судит прогон ТОЛЬКО свои записи (`asker`). Мигратор и сверка задают
    пересекающиеся, но разные наборы вопросов: вопрос про расходящийся шаблон
    задаёт только мигратор, и сверка, посчитав «его никто не задаёт, значит он
    закрыт», стирала бы чужую память — после чего правка шаблона руками
    проходила бы молча (ревьюер, круг 1).
    """
    entries, ledger_rejected, read_error = read_ledger(root)
    tree = tree_version(root)
    asker = current_asker() if asker is None else str(asker)
    asked = list(questions or [])
    asked_keys = set()
    open_keys = set()
    asked_addresses = set()
    by_key = {}
    for question in asked:
        key = question_key(question)
        by_key[key] = question
        asked_keys.add(key)
        asked_addresses.add(question_address(question))
        if key not in deferrals or not deferrable(question):
            open_keys.add(key)

    kept, unconfirmed, by_option = [], [], []
    untracked, vanished, unreadable = [], [], []
    seen = set()
    spent = {}
    for entry in entries:
        key = str(entry.get("key") or "")
        mine = str(entry.get("asker") or "") == asker
        # Дедупликация по ПАРЕ «вопрос и его автор»: без неё каждый прогон
        # дописывал бы ещё одну копию своей же записи, журнал рос бы без
        # конца, а одно решение предъявлялось бы PM столько раз, сколько
        # прогонов было до него (ревьюер, круг 2).
        ident = (key, entry.get("asker"), entry.get("tree"))
        if ident in seen:
            continue
        seen.add(ident)
        if key in open_keys:
            # Вопрос всё ещё открыт: решать нечего, слепок остаётся ТОТ ЖЕ —
            # обновить его значило бы каждый прогон сдвигать точку отсчёта.
            # СТАТУС предмета при этом дозаполняется: поле появилось позже
            # самих записей, а обновление плагина посреди инцидента оставляло
            # запись без него — и команда отсрочки, читающая журнал, отвечала
            # «отложено» там, где гейт запись не засчитает. Слепка это не
            # касается: справочное поле в сумму не входит.
            if (entry.get("status") is None
                    and str(entry.get("kind") or "") in _STATUS_SUBJECT_KINDS):
                entry = dict(entry, status=one_line(
                    by_key[key].get("status") or ""))
            kept.append(entry)
            continue
        if not mine or str(entry.get("tree") or "") != tree:
            # Чужая запись или запись с другой версии дерева. Обе НЕ судятся
            # и НЕ удаляются. Порядок важен: раньше проверка «про этот адрес
            # спрашивают заново» стояла выше и выбрасывала запись соседней
            # ветки, у которой тот же адрес спрашивается другим ключом
            # (ревьюер, круг 2).
            kept.append(entry)
            continue
        if key not in asked_keys and question_address(entry) in asked_addresses:
            # Про тот же предмет спрашивают заново ДРУГИМ вопросом (статус
            # сменился с одного неизвестного значения на другое) — вопрос
            # переформулирован, а не закрыт. Старая запись уступает место
            # новой. Условие «другим вопросом» обязательно: отложенный вопрос
            # задаётся по-прежнему, и без него его запись пропадала бы, а
            # правка предмета под отсрочкой проходила бы молча.
            continue
        recorded = entry.get("subject") or {}
        item = _entry_item(entry)
        if not recorded.get("tracked"):
            item["detail"] = one_line(recorded.get("detail")
                                      or "предмет не отслеживается")
            untracked.append(item)
            continue
        current = subject_fingerprint(root, state, entry)
        if current.get("unreadable"):
            # Файл есть, но не читается. Это НЕ исчезновение: сказать «удалён»
            # и снять запись значило бы потерять память из-за прав доступа
            # (ревьюер, круг 2). Называется и остаётся до следующего раза.
            item["detail"] = one_line(current.get("detail")
                                      or "предмет не прочитан")
            unreadable.append(item)
            kept.append(entry)
            continue
        if not current.get("present"):
            # Предмета больше нет — артефакт удалён или переименован. Это не
            # запись ложного факта в проект: решать больше нечего и нечем.
            # Называется один раз и снимается с учёта (оба ревьюера).
            item["detail"] = "предмет исчез (удалён или переименован)"
            vanished.append(item)
            continue
        digest = current.get("digest")
        record = decisions.get(key) or deferrals.get(key)
        if record is not None and entry.get("resolvedRecord") != record.get("digest"):
            # Человек назвал решение — и запись ФИКСИРУЕТ состояние предмета
            # на ЭТОТ момент, а не снимается. Каждая запись человека
            # расходуется ровно один раз (её опознаёт собственная контрольная
            # сумма): иначе одно подтверждение разрешало бы ВСЕ будущие
            # правки того же предмета, а отсрочка («решим позже») читалась бы
            # как «пиши что хочешь» (ревьюер, круг 1).
            marked = _mark_resolved(entry, digest, record.get("digest"),
                                    "decided" if key in decisions else "deferred")
            spent[key] = marked
            kept.append(marked)
            continue
        if digest == recorded.get("digest") or digest == entry.get("resolvedDigest"):
            kept.append(entry)            # ничего из сторожимого не двигали
            continue
        option = answering_option(entry, argv)
        if option is not None:
            item["option"] = one_line(option)
            by_option.append(item)
            kept.append(_mark_resolved(entry, digest, None, "option"))
            continue
        if confirm_command is not None:
            item["confirm_command"] = confirm_command(key)
        unconfirmed.append(item)
        # Запись ОСТАЁТСЯ: иначе повторный прогон снял бы отказ сам собой, и
        # барьер оказался бы лежачим полицейским, который переезжают дважды.
        kept.append(entry)

    # Слепок заводится на КАЖДЫЙ заданный вопрос, включая отложенный: без
    # него отсрочка была бы дырой — записи нет, сверять нечем, и правка
    # предмета прошла бы молча.
    for key in sorted(asked_keys):
        if (key, asker, tree) in seen:
            continue
        question = by_key[key]
        fresh = {
            "key": key,
            "kind": question.get("kind"),
            "id": question.get("id"),
            "path": question.get("path") or question.get("silo"),
            "asker": asker,
            "tree": tree,
            "askedAt": utc_timestamp(),
            "subject": subject_fingerprint(root, state, question),
        }
        if fresh["kind"] in _STATUS_SUBJECT_KINDS:
            # СТАТУС предмета — в журнале, а не только в отчёте прогона.
            # Команда отсрочки гейт не считает и знает про вопрос ровно то,
            # что записано здесь; без этого поля она не могла отличить
            # «неизвестный статус» от записанного человеком исхода с битой
            # формой, и второй откладывался как первый.
            fresh["status"] = one_line(question.get("status") or "")
        record = decisions.get(key) or deferrals.get(key)
        if record is not None:
            # Запись человека, уже лежащая в состоянии, расходуется ПРЯМО
            # ЗДЕСЬ, на состоянии предмета в момент заведения слепка. Иначе
            # новая запись (например у второго инструмента) считала бы
            # старое подтверждение свежим и закрыла бы им следующую правку
            # (ревьюер, круг 2).
            fresh = _mark_resolved(
                fresh, (fresh["subject"] or {}).get("digest"),
                record.get("digest"),
                "decided" if key in decisions else "deferred")
        kept.append(fresh)

    # Расход записи человека — свойство ВОПРОСА, а не одной записи журнала:
    # у мигратора и сверки записи разные, и подтверждение, потраченное одним,
    # второй считал бы свежим и закрыл бы им уже следующую правку (ревьюер,
    # круг 2). Метка ставится всем записям того же вопроса на ЭТОЙ версии
    # дерева — на чужой версии состояние предмета другое, и переносить метку
    # туда значило бы утверждать про неё то, чего не проверяли.
    if spent:
        kept = [
            _mark_resolved(e, spent[e["key"]].get("resolvedDigest"),
                           spent[e["key"]].get("resolvedRecord"),
                           spent[e["key"]].get("resolvedBy"))
            if (e.get("key") in spent
                and str(e.get("tree") or "") == tree
                and e.get("resolvedRecord") != spent[e["key"]].get("resolvedRecord"))
            else e
            for e in kept
        ]

    barrier = {
        "ledger": LEDGER_REL,
        "tracked_rules": list(TRACKED_SUBJECT_RULES),
    }
    if read_error:
        barrier["read_error"] = read_error
    if ledger_rejected:
        barrier["rejected_entries"] = ledger_rejected
    # `or ledger_rejected`: журнал, состоящий из одних негодных записей, после
    # фильтрации равен `kept` — и без этого условия он никогда не
    # переписывался бы, а «отброшена и посчитана» превращалось в вечное
    # повторение одного и того же предупреждения (ревьюер, круг 2).
    if kept != entries or ledger_rejected:
        write_error = write_ledger(root, kept)
        if write_error:
            # Журнал не записан — значит следующий прогон сверять будет не с
            # чем. Молчание об этом обещало бы защиту, которой не будет.
            barrier["write_error"] = write_error
    out = {"decision_barrier": barrier}
    if unconfirmed:
        out["decisions_unconfirmed"] = unconfirmed
    if by_option:
        out["decisions_by_option"] = by_option
    if untracked:
        out["decisions_untracked"] = untracked
    if vanished:
        out["decisions_vanished"] = vanished
    if unreadable:
        out["decisions_unreadable"] = unreadable
    return out


# ── вердикт ────────────────────────────────────────────────────────────────

def evaluate(questions, state, enforced=False, defer_command=None,
             recheck_command=None, root=None, argv=None, gated=None,
             confirm_command=None):
    """Вердикт гейта по вопросам ЭТОГО прогона и отсрочкам из состояния.

    `enforced` — «результат этого прогона уезжает наружу». Истинно ровно у
    пишущего прогона: он оставил в дереве изменения, которые дальше пойдут в
    коммит и PR. У прогона без записи (dry-run, `up_to_date`, `in_sync`)
    следующий шаг — решение PM, а не публикация, и отказ там был бы ложным:
    именно ложные срабатывания приучают обходить гейты. Вопросы такой прогон
    всё равно НАЗЫВАЕТ — молчать о них он не начинает.

    `gated` — «этот прогон не объявлен шагом внутри цикла». Второе плечо
    гейта (решение, принятое правкой предмета) держится на нём, а не на
    `enforced`, и это РАЗНЫЕ вещи: открытый вопрос — свойство прогона, чей
    результат уезжает наружу, а непризнанное решение уже лежит в проекте, и
    прогон, который его увидел, обязан остановиться, даже если сам ничего не
    записал. Умолчание — `enforced`: вызывающий, не знающий про второе плечо,
    получает поведение #404 без изменений.

    `root` включает второе плечо. Без него (прямой вызов из теста или чужого
    кода) гейт остаётся ровно тем, чем был.
    """
    deferrals, rejected = read_deferrals(state)
    decisions, rejected_decisions = read_decisions(state)
    open_items = []
    deferred_items = []
    for question in questions or []:
        key = question_key(question)
        entry = {
            "key": key,
            "kind": question.get("kind"),
            # Адрес — тоже ЧУЖОЙ текст: имя файла на POSIX может содержать
            # перевод строки, и без нормализации он добавил бы в блок для PM
            # строку, которой инструмент не писал, а в тело PR — пункт списка
            # (оба ревьюера, круг 1). Нормализация стоит ЗДЕСЬ, у источника:
            # блоков, печатающих эти поля, уже три, и правило, записанное в
            # каждом из них, разошлось бы молча.
            "id": _address(question.get("id")),
            "path": _address(question.get("path") or question.get("silo")),
            "question": one_line(question.get("question")
                                 or question.get("detail") or ""),
        }
        if entry["kind"] in _STATUS_SUBJECT_KINDS:
            # «Сколько и КАКИХ» — требование отчёта, и значение обязано ехать
            # полем, а не вычитываться из формулировки: текст вопроса
            # переписывается обновлением плагина, значение — нет. Поле кладут
            # ОБА класса про статус, а не только исход: по нему команда
            # отсрочки узнаёт, что за ключом стоит решение человека, даже
            # когда вопрос приехал соседним классом из-за битой формы.
            entry["status"] = one_line(question.get("status") or "")
        can_defer = deferrable(entry)
        record = deferrals.get(key) if can_defer else None
        if record is None:
            # Готовая команда печатается только там, где она СРАБОТАЕТ.
            # Раньше она приписывалась любому открытому вопросу, и у исхода с
            # битой формой рецепт печатал PM команду, которую та же поставка
            # гарантированно отвергает: мёртвый маршрут в единственном тексте,
            # который копируют дословно. Рабочий путь у этого класса — ветка
            # «A. ОТВЕТИТЬ» того же отказа: исправить запись статуса.
            if defer_command is not None and can_defer:
                entry["defer_command"] = defer_command(key)
            if entry["kind"] == OUTCOME_KIND and confirm_command is not None:
                # У этого класса главный путь — ПРИЗНАТЬ, а не отложить:
                # вопрос не в том, каким быть статусу, а в том, кто его
                # выбрал. Готовая команда печатается рядом с вопросом по
                # тому же замеренному правилу, что и все остальные.
                entry["confirm_command"] = confirm_command(key)
            open_items.append(entry)
        else:
            entry["reason"] = one_line(record.get("reason"))
            # Время записи — тоже чужой текст: `\r` в нём перерисовал бы строку
            # отчёта поверх напечатанной (ревьюер, круг 1). Одна строка — один
            # контракт на всё, что печатается PM'у.
            entry["recordedAt"] = one_line(record.get("recordedAt"))
            deferred_items.append(entry)
    gate = {
        "status": GATE_BLOCKED if open_items else GATE_CLEAR,
        "enforced": bool(enforced),
        # ОБЪЯВЛЕННЫЙ шаг внутри цикла — отдельно от `enforced`, и это разные
        # факты. `enforced` ложно и у прогона, который просто ничего не пишет:
        # там гейт не применяется потому, что применять нечего. Здесь гейт
        # выключен РЕШЕНИЕМ вызывающего, и только этот случай стоит печатать.
        # Источник у флага один — `is_intermediate`, тот же, что у условия на
        # пишущем пути: второе написание разошлось бы молча.
        "intermediate": is_intermediate(argv),
        "open": open_items,
        "deferred": deferred_items,
        # Сколько ЗАСЧИТАННЫХ отсрочек в проекте. `deferred` — только те,
        # чей вопрос задан ЭТИМ прогоном, и как только условие исчезает,
        # вопрос перестаёт задаваться, а отсрочка пропадает из списка. Без
        # этого числа отчёт обещал бы постоянную видимость, которой у списка
        # нет (ревьюер, круг 1): счётчик её и даёт.
        "recorded_total": len(deferrals),
    }
    if open_items and not enforced:
        gate["detail"] = (
            "Наружу из этого прогона ничего не уходит (он либо ничего не "
            "записал, либо объявлен шагом внутри цикла опцией `%s`) — гейт "
            "вопросы НАЗЫВАЕТ, но прогон не останавливает. Отказом "
            "закончится пишущий прогон, результат которого поедет в коммит "
            "и PR." % INTERMEDIATE_OPT)
    if rejected:
        gate["rejected_records"] = rejected
    if rejected_decisions:
        gate["rejected_decisions"] = rejected_decisions
    marked = agent_session_records(deferrals, decisions)
    if marked:
        # Поле появляется ТОЛЬКО когда есть что сказать: там, где все решения
        # приняты человеком в своём терминале, метки нет ни одной — и тогда
        # молчит всё, ни поля, ни строки, ни счётчика. Отсутствие метки и
        # есть «решение человека», и дописывать к нему пустой раздел значило
        # бы сделать тишину неразличимой.
        gate["agent_session_records"] = marked
        gate["agent_session_barrier"] = {
            "census": agent_session_census(marked),
            "limits": list(AGENT_SESSION_LIMITS),
        }
    if recheck_command is not None:
        gate["recheck_command"] = recheck_command
    waiting = outcome_items(gate)
    if waiting:
        # Поле появляется ТОЛЬКО когда есть что сказать: на проекте без таких
        # артефактов барьер молчит целиком — ни поля, ни строки, ни счётчика.
        # Объявленная граница едет вместе с отказом: частичную защиту нельзя
        # выдавать за полную, а перечень, лежащий только в исходнике, до PM
        # не доезжает.
        gate["outcomes_unacknowledged"] = waiting
        gate["outcome_barrier"] = {
            "outcomes": sorted(NON_SUCCESS_OUTCOMES),
            "census": outcome_census(waiting),
            "limits": list(OUTCOME_BARRIER_LIMITS),
            # Условие ТРЕТЬЕГО плеча — `gated`, как у второго, а не
            # `enforced`. И по той же причине: решение уже лежит в проекте,
            # и прогон, который его увидел, обязан остановиться, даже если
            # сам ничего не записал. На `enforced` барьер получился бы
            # неправдой ровно там, где issue настаивает: проект, у которого
            # мигрировать и сверять нечего, никогда не дошёл бы до отказа, и
            # «разовое признание уже существующего» не потребовалось бы
            # никогда.
            "enforced": bool(enforced if gated is None else gated),
        }
    if root is not None:
        gate.update(reconcile_decisions(
            root, state, questions, deferrals, decisions,
            argv=argv, confirm_command=confirm_command))
        gate["decision_barrier"]["enforced"] = bool(
            enforced if gated is None else gated)
        if gate.get("decisions_unconfirmed"):
            gate["status"] = GATE_BLOCKED
        gate["decisions_recorded_total"] = len(decisions)
    return gate


#: Что печатается, когда гейт выключен объявлением вызывающего.
#:
#: Замерено: прогон `--apply --intermediate-step` с нулём вопросов выдавал
#: тело PR и блок PM, БАЙТ-В-БАЙТ совпадающие с честно чистым прогоном, а
#: единственное различие (`pm_gate.enforced`) лежало в JSON, который PM по
#: замеру не читает. Для записей решений построена метка происхождения, а у
#: флага, выключающего весь гейт, метки не было вовсе — то есть единственный
#: массовый обход был невидим ровно там, где конструкция обещает видимость.
#: Обход при этом остаётся разрешённым: закрывается не он, а его незаметность.
UNENFORCED_NOTE = (
    "Гейт в этом прогоне НЕ применялся: прогон объявлен шагом внутри цикла "
    "опцией `%s`. Вопросы он называет, но прогон не останавливает."
    % INTERMEDIATE_OPT)


def unenforced_note(gate) -> str:
    """Строка про выключенный гейт, либо пусто. ОДИН источник на оба носителя.

    Носителей два — готовая строка отчёта и раздел тела PR, — и текст у них
    обязан быть один: две формулировки одного факта расходятся молча, а здесь
    расхождение означало бы, что в PR и в отчёте написано разное про то, был
    ли гейт включён.
    """
    return UNENFORCED_NOTE if (gate or {}).get("intermediate") else ""


def blocked(gate) -> bool:
    """Прогон заканчивается отказом. Три плеча, у каждого своё условие.

    Плечо #404: вопрос открыт И результат прогона уезжает наружу.
    Плечо #406: решение принято правкой предмета и никем не названо — здесь
    достаточно того, что прогон не объявлен шагом внутри цикла. Ложный факт
    уже записан в проект, и dry-run, который его увидел, обязан остановиться:
    следующим шагом после dry-run идёт `--apply`, а не решение PM.
    Плечо #408: исход, который принимает человек, лежит в артефакте без
    признания. Условие то же, что у второго плеча, и по той же причине:
    предмет спора уже в проекте, а не рождается этим прогоном.
    """
    if not gate:
        return False
    if gate.get("status") == GATE_BLOCKED and gate.get("open") \
            and gate.get("enforced"):
        return True
    if gate.get("decisions_unconfirmed") \
            and (gate.get("decision_barrier") or {}).get("enforced"):
        return True
    return bool(gate.get("outcomes_unacknowledged")) and bool(
        (gate.get("outcome_barrier") or {}).get("enforced"))


def summary_suffix(gate) -> str:
    """Хвост готовой строки отчёта — то, что насчитало ВТОРОЕ плечо гейта.

    Без него строка, которую рецепт печатает дословно, кончалась словами
    «Вопросов PM: 0» ровно в том прогоне, который остановлен из-за решения по
    вопросу PM: вопроса действительно уже нет, его закрыли правкой. Число
    считает инструмент — тот же замеренный рычаг, что и весь `summary`.

    «Прогон остановлен» пишется только там, где он ДЕЙСТВИТЕЛЬНО остановлен:
    шаг внутри цикла решение называет, но заканчивается нулём, и готовая
    строка, утверждающая обратное, противоречила бы коду возврата в том
    единственном тексте, который рецепт копирует дословно (ревьюер, круг 1).
    """
    out = ""
    note = unenforced_note(gate)
    if note:
        out += " " + note
    waiting = outcome_items(gate)
    if waiting:
        # «Сколько исходов ждут признания и каких» — счётом инструмента, а не
        # пересказом модели. Соседнее число («Вопросов PM: N») этот класс уже
        # включает, но не называет: из «Вопросов PM: 1» не видно, что спорным
        # является решение, а не статус.
        out += (" Исходов, записанных в артефакты и не признанных PM: %d (%s)%s."
                % (len(waiting), outcome_census(waiting),
                   " — прогон остановлен"
                   if blocked(gate) and (gate or {}).get(
                       "outcome_barrier", {}).get("enforced") else ""))
    # Метка попадает и в готовую строку, и отдельным блоком, и это не
    # дублирование ради красоты: строку рецепт печатает дословно, а блок
    # читает PM глазами. Потерять факт должны оба носителя сразу, чтобы он
    # исчез. Группы названы ПО ОТДЕЛЬНОСТИ: сложить их в одно число значило бы
    # приписать установленное происхождение записям, у которых его нет.
    for title, rows in agent_session_groups(agent_session_items(gate)):
        if title == AGENT_SESSION_TITLE:
            out += (" Записей решений PM, сделанных изнутри агентской сессии: "
                    "%d (%s)." % (len(rows), agent_session_census(rows)))
        else:
            out += (" Записей решений PM, чьё происхождение не установлено: "
                    "%d (%s)." % (len(rows), agent_session_census(rows)))
    count = len((gate or {}).get("decisions_unconfirmed") or [])
    if count:
        out += (" Решений по вопросам PM, принятых правкой и никем не "
                "названных: %d%s." % (count, " — прогон остановлен"
                                      if blocked(gate) else ""))
    barrier = (gate or {}).get("decision_barrier") or {}
    if barrier.get("read_error") or barrier.get("write_error"):
        out += (" ⚠ Журнал гейта недоступен (%s) — следующему прогону сверять "
                "будет не с чем."
                % one_line(barrier.get("write_error")
                           or barrier.get("read_error")))
    return out


def run_status(gate, ok_status) -> tuple:
    """`(статус прогона, код возврата)` с учётом ВСЕХ плеч гейта.

    Одна функция на оба инструмента и на все их точки выдачи: статус, который
    каждая точка выбирала бы себе сама, разошёлся бы молча — и разошёлся бы
    именно там, где прогон заканчивается отказом.

    Когда верны ОБА условия, статус называет плечо решения, а не открытого
    вопроса, и порядок здесь именно поэтому: непризнанное решение — ложный
    факт, УЖЕ записанный в проект, а открытый вопрос это всего лишь решение,
    которого ещё нет. Отказ при этом печатает оба блока: статус выбирает, чем
    назвать прогон, а не о чём молчать.
    """
    if not blocked(gate):
        return ok_status, 0
    if gate.get("decisions_unconfirmed") \
            and (gate.get("decision_barrier") or {}).get("enforced"):
        return BLOCKED_DECISION_STATUS, BLOCKED_EXIT
    if gate.get("outcomes_unacknowledged") \
            and (gate.get("outcome_barrier") or {}).get("enforced"):
        return BLOCKED_OUTCOME_STATUS, BLOCKED_EXIT
    return BLOCKED_STATUS, BLOCKED_EXIT


# ── готовый текст для PM ───────────────────────────────────────────────────

def refusal_lines(gate) -> list:
    """Готовый блок отказа. Собирать нечего, сокращать нечего.

    Тот же замеренный рычаг, что и `summary`/`pm_block`: печатает ИНСТРУМЕНТ,
    модель только копирует. Команды здесь готовые, с подставленными путями, —
    именно готовую команду модель донесла дословно в замере про `--yes`.
    """
    # Непризнанные исходы печатаются СВОИМ блоком: у них другой разговор.
    # «Ответить или отложить» здесь читается как предложение решить то, что
    # уже решено, а главный путь — назвать автора решения.
    waiting = outcome_items(gate)
    waiting_keys = {item.get("key") for item in waiting}
    open_items = [item for item in gate.get("open") or []
                  if item.get("key") not in waiting_keys]
    unconfirmed = list(gate.get("decisions_unconfirmed") or [])
    lines = []
    if waiting and (gate.get("outcome_barrier") or {}).get("enforced"):
        lines += outcome_refusal_lines(gate)
        if open_items:
            lines.append("")
    if open_items and gate.get("enforced"):
        lines += [
            _RULE,
            "⛔ ВЫХОД НАРУЖУ ЗАБЛОКИРОВАН: неотвеченные вопросы к PM",
            _RULE,
            "",
            "Работа выполнена, файлы записаны и лежат локально — ничего не "
            "пропало.",
            "НЕ выполняются: коммит, push и PR. Это отказ, а не результат.",
            "",
            "Открытых вопросов: %d" % len(open_items),
        ]
        for i, item in enumerate(open_items, 1):
            head = "%d. [%s] %s" % (i, item["key"], item.get("id") or "—")
            if item.get("path"):
                head += " (%s)" % item["path"]
            lines.append(head)
            if item.get("question"):
                lines.append("   %s" % item["question"])
        lines += ["", "Два пути, оба явные:", ""]
        recheck = gate.get("recheck_command")
        if recheck:
            lines += [
                "A. ОТВЕТИТЬ — исправь условие в артефакте, затем повтори "
                "проверку:",
                "   %s" % recheck,
                "",
            ]
        deferrable_items = [i for i in open_items if i.get("defer_command")]
        if deferrable_items:
            lines.append("B. ОТЛОЖИТЬ — причина обязательна и остаётся в "
                         "состоянии проекта, в отчёте и в теле PR:")
            for item in deferrable_items:
                lines.append("   %s" % item["defer_command"])
        rejected = gate.get("rejected_records") or []
        if rejected:
            lines += ["", "Отвергнутые записи отсрочек: %d" % len(rejected)]
            for rec in rejected:
                lines.append("   [%s] %s" % (rec.get("key") or "—",
                                             rec.get("detail") or ""))
        lines += ["", _RULE]
    if unconfirmed:
        if lines:
            lines.append("")
        lines += decision_refusal_lines(gate)
    return lines


def outcome_refusal_lines(gate) -> list:
    """Готовый блок отказа ТРЕТЬЕГО плеча: исход записан, признания нет.

    Отдельный текст, а не строка среди прочих вопросов: здесь спорен не
    статус, а то, КТО его выбрал, и совет «исправь условие в артефакте»
    читался бы как предложение переписать чужое решение. Граница барьера
    печатается вместе с отказом — объявленная дыра честнее необъявленной, и
    до PM доезжает только то, что напечатано.
    """
    waiting = outcome_items(gate)
    lines = [
        _RULE,
        "⛔ ВЫХОД НАРУЖУ ЗАБЛОКИРОВАН: исход артефакта не признан PM",
        _RULE,
        "",
        "Отмена, неактуальность и неприменимость — РЕШЕНИЯ человека, а не "
        "факты",
        "о коде. Ни один из перечисленных исходов не назван записью PM, и "
        "неважно,",
        "когда он появился: барьер смотрит на состояние, а не на правку.",
        "НЕ выполняются: коммит, push и PR.",
        "",
        "Исходов без признания: %d (%s)" % (len(waiting),
                                            outcome_census(waiting)),
    ]
    for i, item in enumerate(waiting, 1):
        head = "%d. [%s] %s" % (i, item.get("key") or "—",
                                item.get("id") or "—")
        if item.get("path"):
            head += " (%s)" % item["path"]
        lines.append("%s — `%s`" % (head, item.get("status") or "?"))
    lines += ["", "Два пути, оба явные:", ""]
    lines += [
        "A. ИСПРАВИТЬ — если исход записан неверно, поставь артефакту статус,",
        "   соответствующий действительности, и повтори проверку.",
        "",
        "B. ПРИЗНАТЬ — если исход выбрал ты, назови решение: причина "
        "обязательна",
        "   и остаётся в состоянии проекта, в отчёте и в теле PR.",
    ]
    for item in waiting:
        if item.get("confirm_command"):
            lines.append("   %s" % item["confirm_command"])
    lines += ["", "Что этот барьер НЕ ловит (названо, а не умолчано):"]
    lines += ["   — %s" % limit for limit in OUTCOME_BARRIER_LIMITS]
    lines += ["", _RULE]
    return lines


def decision_refusal_lines(gate) -> list:
    """Готовый блок отказа ВТОРОГО плеча: решение принято правкой предмета.

    Отдельный текст, а не строка в блоке вопросов: вопроса уже нет, и совет
    «ответь или отложи» здесь читался бы как предложение решить то, что уже
    решено. Разговор другой — назвать решение или вернуть предмет.
    """
    unconfirmed = list(gate.get("decisions_unconfirmed") or [])
    lines = [
        _RULE,
        "⛔ ВЫХОД НАРУЖУ ЗАБЛОКИРОВАН: решение по вопросу PM принято правкой",
        _RULE,
        "",
        "Вопрос к PM закрылся не ответом, а изменением самого предмета — и "
        "никто",
        "не назвал себя автором решения. Кто правил файл, механизму "
        "неизвестно:",
        "это отказ, а не обвинение. НЕ выполняются: коммит, push и PR.",
        "",
        "Решений без автора: %d" % len(unconfirmed),
    ]
    for i, item in enumerate(unconfirmed, 1):
        head = "%d. [%s] %s" % (i, item.get("key") or "—", item.get("id") or "—")
        if item.get("path"):
            head += " (%s)" % item["path"]
        lines.append(head)
        lines.append("   Предмет: %s — сдвинулся после того, как вопрос был "
                     "задан%s." % (item.get("subject") or "—",
                                   " " + str(item.get("askedAt"))
                                   if item.get("askedAt") else ""))
    lines += ["", "Два пути, оба явные:", ""]
    lines += [
        "A. ВЕРНУТЬ — если правку делал не человек, верни предмет в прежнее "
        "состояние;",
        "   вопрос задастся снова, и на него можно будет ответить или "
        "отложить.",
        "",
        "B. ПРИЗНАТЬ — если решение принимал ты, назови его: причина "
        "обязательна",
        "   и остаётся в состоянии проекта, в отчёте и в теле PR.",
    ]
    for item in unconfirmed:
        if item.get("confirm_command"):
            lines.append("   %s" % item["confirm_command"])
    for label, field in (("Предмет исчез — решать нечем", "decisions_vanished"),
                         ("Предмет НЕ ПРОЧИТАН — сверка отложена",
                          "decisions_unreadable"),
                         ("Предмет НЕ сторожится — сверять нечем",
                          "decisions_untracked")):
        rows = gate.get(field) or []
        if not rows:
            continue
        lines += ["", "%s (%d):" % (label, len(rows))]
        for rec in rows:
            lines.append("   [%s] %s — %s" % (rec.get("key") or "—",
                                              rec.get("path") or rec.get("id")
                                              or "—",
                                              rec.get("detail") or ""))
    lines += _barrier_warning_lines(gate)
    lines += ["", _RULE]
    return lines


def _barrier_warning_lines(gate) -> list:
    """Сбои самого барьера — строками, а не только полем в JSON.

    Ненаписанный журнал значит, что следующий прогон сверять будет НЕ С ЧЕМ:
    молчание об этом обещало бы защиту, которой не будет (ревьюер, круг 1).
    """
    barrier = (gate or {}).get("decision_barrier") or {}
    out = []
    for field, label in (("read_error", "журнал гейта"),
                         ("write_error", "журнал гейта")):
        if barrier.get(field):
            out.append("   ⚠ %s: %s — на следующем прогоне сверять будет не "
                       "с чем." % (label, one_line(barrier[field])))
    if barrier.get("rejected_entries"):
        out.append("   ⚠ записей журнала отвергнуто по форме: %s"
                   % barrier["rejected_entries"])
    return out


def pr_body_lines(gate, heading="### Гейт вопросов PM") -> list:
    """Раздел тела PR. Общий у обоих инструментов — форма одна.

    Заголовок раздела называет МОМЕНТ («на момент прогона»): тело PR пишется
    прогоном, а отсрочка может быть записана после него. Без этой оговорки
    раздел утверждал бы про настоящее то, что верно про прошлое.
    """
    if not gate:
        return []
    open_items = gate.get("open") or []
    deferred = gate.get("deferred") or []
    rejected = gate.get("rejected_records") or []
    out = [heading, "",
           "Статус на момент прогона: `%s`." % gate.get("status", "?"), ""]
    note = unenforced_note(gate)
    if note:
        out += ["> ⚠️ %s" % note, ""]
    out.append("**Открыто (%d)**" % len(open_items))
    out += (["- `%s` — %s" % (i["key"], one_line(i.get("question") or ""))
             for i in open_items] or ["- _Ни одного._"])
    out.append("")
    out.append("**Отложено с причиной (%d)**" % len(deferred))
    out += (["- `%s` — %s (записано %s)"
             % (i["key"], one_line(i.get("reason") or ""),
                i.get("recordedAt") or "?")
             for i in deferred] or ["- _Ни одной._"])
    if rejected:
        out += ["", "**Отвергнутые записи отсрочек (%d)**" % len(rejected)]
        out += ["- `%s` — %s" % (r.get("key") or "?", r.get("detail") or "")
                for r in rejected]
    # Исходы без признания — своим разделом, со счётом и перечнем: ревьюер
    # обязан видеть, СКОЛЬКО решений за PM лежит в этом изменении и КАКИХ.
    # Они же остаются в «Открыто» выше: убрать их оттуда значило бы
    # напечатать «Открыто (0)» на прогоне, который именно ими и остановлен.
    waiting = outcome_items(gate)
    if waiting:
        out += ["", "**Исходы артефактов без признания PM (%d: %s)**"
                    % (len(waiting), outcome_census(waiting))]
        # Адрес кодовым спаном: он рендерит разметку и открывающий
        # HTML-комментарий из чужого имени файла буквально. Ограждение
        # выбирается по содержимому (`md_code`), а не фиксированной одиночной
        # кавычкой: кавычка внутри имени закрыла бы спан досрочно, и остаток
        # адреса уехал бы в разметку (ревьюеры, круги 1 и 2).
        out += ["- `%s` — %s (%s): %s"
                % (i.get("key") or "?", md_code(i.get("id") or "—"),
                   md_code(i.get("path") or "—"),
                   md_code(i.get("status") or "?"))
                for i in waiting]
        out += ["", "Чего этот барьер НЕ ловит:"]
        out += ["- %s" % limit for limit in OUTCOME_BARRIER_LIMITS]

    # Помеченные записи — СВОИМ разделом, а не сноской внутри соседнего:
    # ревьюер обязан видеть, что решение, снявшее гейт, записал процесс,
    # начатый инструментом. Раздел печатается и тогда, когда гейт чист, —
    # это и есть тот прогон, ради которого метка заведена.
    marked = agent_session_items(gate)
    if marked:
        # Раздел собирает ОБЩИЙ рендер — тот же, которым его дописывает
        # команда записи: заголовок и перечень границы обязаны быть одними и
        # теми же байтами в обоих носителях.
        out += [""] + agent_session_pr_lines(marked)

    # Второе плечо едет в тело PR ВСЕГДА, когда есть что сказать, — и это
    # второй носитель того же факта, не замена отказа: отказ видит PM, а
    # тело PR читает ревьюер, и до него отказ не доезжает вовсе.
    unconfirmed = gate.get("decisions_unconfirmed") or []
    if unconfirmed:
        out += ["", "**Решение принято правкой предмета, автор не назван "
                    "(%d)**" % len(unconfirmed)]
        out += ["- `%s` — %s (%s); предмет: %s"
                % (i.get("key") or "?", md_code(i.get("id") or "—"),
                   md_code(i.get("path") or "—"), i.get("subject") or "—")
                for i in unconfirmed]
    by_option = gate.get("decisions_by_option") or []
    if by_option:
        out += ["", "**Закрыто опцией этого прогона (%d)**" % len(by_option)]
        out += ["- `%s` — %s (опция `%s`)"
                % (i.get("key") or "?", i.get("id") or "—",
                   one_line(i.get("option") or "?"))
                for i in by_option]
    for label, field in (
            ("Закрыто без сверки предмета — класс не сторожится",
             "decisions_untracked"),
            ("Предмет вопроса исчез (удалён или переименован)",
             "decisions_vanished"),
            ("Предмет вопроса не прочитан — сверка отложена",
             "decisions_unreadable")):
        rows = gate.get(field) or []
        if not rows:
            continue
        out += ["", "**%s (%d)**" % (label, len(rows))]
        out += ["- `%s` — %s" % (one_line(i.get("key") or "?"),
                                 one_line(i.get("detail") or ""))
                for i in rows]
    warnings = _barrier_warning_lines(gate)
    if warnings:
        out += ["", "**Сбои барьера решений**"]
        out += ["- %s" % w.strip() for w in warnings]
    return out


