def outcome_like(item) -> bool:
    """Вопрос ли это про ИСХОД, который принимает человек. ОДИН источник.

    Классов-носителей два, и разделение между ними — форма записи, а не суть
    спора. Когда исход записан правильно, спрашивает `artifact-outcome-…`.
    Когда та же отмена записана НЕВЕРНОЙ формой (пустая причина, `not_actual`
    не у BUG), про артефакт спрашивает соседний класс `artifact-status-…` — и
    он откладываемый. Замерено: отмена с пустой причиной откладывалась
    командой отсрочки (rc=0), после чего гейт отвечал `clear`, хотя в
    frontmatter лежало `status: cancelled`. То есть решение за PM закрывалось
    словами «разберусь позже» — ровно то, что третий барьер запрещает.

    Решает не класс вопроса, а СТАТУС предмета: он и есть то, что делает
    вопрос решением человека.
    """
    item = item or {}
    kind = str(item.get("kind") or "")
    if kind == OUTCOME_KIND:
        return True
    return (kind == UNKNOWN_STATUS_KIND
            and str(item.get("status") or "") in NON_SUCCESS_OUTCOMES)


def deferrable(question) -> bool:
    """Закрывает ли ОТСРОЧКА этот вопрос.

    Принимает ВОПРОС, а не только его класс: класса мало — та же отмена
    приезжает двумя классами в зависимости от того, верна ли форма записи
    (см. `outcome_like`).

    Для исхода — нет, и это не мелочь формы. «Решим позже» у вопроса «кто это
    решил» означает «решение уже принято, а кем — разберусь потом», то есть
    ровно то тихое решение за PM, ради которого барьер и заведён (оба
    ревьюера, круг 1). Вдобавок отсрочка не привязана к состоянию предмета:
    ключ вопроса не включает причину исхода, и одна отсрочка закрывала бы и
    все последующие переписывания причины.

    Предикат ОДИН на всех, кто спрашивает «закрыт ли вопрос»: два написания
    этого правила разошлись бы молча, и вопрос оказался бы открытым у одного
    читателя и закрытым у другого.
    """
    return not outcome_like(question)


def outcome_address(item) -> str:
    """Адрес исхода — то, к чему привязана запись признания.

    Идентификатор, а не путь, когда он есть: переименование файла не
    отменяет принятого решения, а путь после него другой. Путь — запасной
    адрес для артефакта без идентификатора.
    """
    ident = one_line(item.get("id") or "").strip()
    if ident:
        return "id:%s" % ident
    # Нормализация минимальная и намеренно одна на обе стороны: оба адреса
    # приходят из одного обхода артефактов, а разделитель приводится к одному
    # виду, чтобы запись, сделанная под Windows, годилась и под POSIX.
    rel = one_line(item.get("path") or "").strip().replace("\\", "/")
    return "path:%s" % rel


def acknowledged_outcomes(decisions) -> set:
    """`{(адрес, слепок)}` из ГОДНЫХ записей признания.

    Пара, а не адрес: признание фиксирует ровно то состояние исхода, которое
    человек видел. Следующая правка тех же полей меняет слепок, и вопрос
    открывается снова — иначе одно признание закрывало бы все будущие правки.
    """
    out = set()
    for record in (decisions or {}).values():
        address = record.get("outcomeAddress")
        subject = record.get("outcomeSubject")
        # Форма проверяется здесь, а не только в разборе записи: поля лежат в
        # JSON, который правит кто угодно, и словарь вместо строки должен
        # давать «не признано», а не исключение посреди сбора вопросов.
        if isinstance(address, str) and address \
                and isinstance(subject, str) and subject:
            out.add((address, subject))
    return out


def outcome_questions(root, state, artifacts) -> list:
    """Вопросы PM про исходы, записанные в артефакты и никем не признанные.

    Предмет — СОСТОЯНИЕ, а не изменение: вопрос задаётся по тому, что лежит
    на диске сейчас, независимо от того, когда это появилось. Барьер,
    опирающийся на «сдвинулось ли с прошлого взгляда», не видит решения,
    принятого ДО первого взгляда, — а замер показал, что модель уходит
    именно туда.

    Артефакт, у которого исход записан НЕВЕРНОЙ формой, пропускается: про
    него уже спрашивает соседний класс (`artifact-status-decision`), и два
    вопроса про один артефакт дали бы два отказа подряд.
    """
    decisions, _rejected = read_decisions(state)
    acknowledged = acknowledged_outcomes(decisions)
    out = []
    for art in artifacts or []:
        status = str(art.get("status") or "")
        if status not in NON_SUCCESS_OUTCOMES:
            continue
        if artifact_status_issue(str(art.get("id") or ""), status,
                                 art.get("status_reason") or "",
                                 art.get("superseded_by") or "") is not None:
            continue
        item = {
            "kind": OUTCOME_KIND,
            "id": art.get("id"),
            "path": art.get("path"),
            "status": status,
            "question": OUTCOME_QUESTION % status,
        }
        digest = subject_fingerprint(root, state, item).get("digest")
        if digest and (outcome_address(item), digest) in acknowledged:
            continue
        out.append(item)
    return out


def outcome_scope(root, state, key):
    """Область действия признания по ключу вопроса, либо None.

    Читается из ЖУРНАЛА гейта: там лежит адрес артефакта, про который вопрос
    задавался, а слепок берётся с диска в момент признания. Поэтому признание
    правки (`--confirm` по вопросу о статусе) признаёт и исход, который эта
    правка записала: человек назвал одно решение один раз, и второго отказа
    подряд про тот же артефакт не будет.

    None — когда сверять нечего: записи с таким ключом в журнале нет, её
    предмет не статус артефакта, или предмет сейчас не читается. Это НЕ
    ошибка команды: признание записывается, просто без привязки к исходу, и
    команда говорит об этом вслух.
    """
    entries, _rejected, _error = read_ledger(root)
    for entry in entries:
        if str(entry.get("key") or "") != str(key):
            continue
        recorded = entry.get("subject") or {}
        if recorded.get("source") != STATUS_SUBJECT_SOURCE:
            continue
        current = subject_fingerprint(root, state, entry)
        if not current.get("present") or not current.get("digest"):
            continue
        return {"address": outcome_address(entry),
                "subject": current["digest"]}
    return None


def outcome_items(gate) -> list:
    """Открытые вопросы про непризнанные исходы — из вердикта гейта."""
    return [item for item in (gate or {}).get("open") or []
            if item.get("kind") == OUTCOME_KIND]


def outcome_census(items) -> str:
    """`cancelled: 2, not_actual: 1` — сколько и КАКИХ исходов ждут признания.

    Считает инструмент, а не модель: замерено на живом прогоне, что счёт по
    списку модель называет неверно, а готовую строку копирует дословно.
    """
    counts = {}
    for item in items or []:
        counts[str(item.get("status") or "?")] = \
            counts.get(str(item.get("status") or "?"), 0) + 1
    return ", ".join("%s: %d" % (name, counts[name]) for name in sorted(counts))


# ── метка «запись сделана изнутри агентской сессии» ────────────────────────
#
# Почему не запрет и почему источник ровно один — в разделе «Четвёртый ход»
# docstring'а модуля; что метка НЕ значит — в разделе «Честная граница
# МЕТКИ» там же и в `AGENT_SESSION_LIMITS` ниже (перечень печатается, а не
# лежит в исходнике: до PM доезжает только напечатанное).

#: Поле-метка в записи решения PM. Значение — имя контура (`gigacode`,
#: `qwen`, `claude-code`, `opencode`), а не булево: «какой инструмент» PM
#: читает без расшифровки, а `true` требует знать, что оно означает.
AGENT_SESSION_FIELD = "recordedInAgentSession"

#: Что метка НЕ значит. Печатается рядом с ней в отчёте и в теле PR.
#: Пункты — класс, а не пример: перечень, состоящий из одного случая,
#: читается как «остальное закрыто».
AGENT_SESSION_LIMITS = (
    "метка говорит про ПРОЦЕСС, а не про автора решения: «эту запись сделал "
    "процесс, начатый инструментом» — и ничего о том, кто нажимал клавиши",
    "переменные окружения снимаются (`env -u …`), и тогда запись выйдет без "
    "метки: это ВИДИМОСТЬ, а не запрет",
    "переменные наследуются: шелл, открытый из агентской сессии, несёт их "
    "дальше, поэтому запись человека ИЗНУТРИ такой сессии тоже помечена",
    "снять или приписать метку правкой состояния незаметно нельзя — она "
    "внутри контрольной суммы записи, — но запись целиком пересобирается: "
    "алгоритм суммы открыт",
)

#: Как называется каждая из двух форм записи там, где её читает человек.
_RECORD_FORM_NAMES = {"deferral": "отсрочка", "decision": "признание"}

#: «Поля метки не было» и «поле метки пустое» — РАЗНЫЕ вещи, и одним `None`
#: они не выражаются: первое законно, второе означает сломанную форму записи.
_MARK_ABSENT = object()


#: Значение метки, когда спросить НЕ У ЧЕГО. Отдельное значение, а не
#: отсутствие поля: «проба недоступна» и «решение человека» — разные ответы, и
#: выражать их одинаково значило бы, что сломанная установка молча выдаёт
#: записи, неотличимые от человеческих (оба ревьюера, круг 1).
AGENT_SESSION_UNKNOWN = "unknown"

#: Как назвать происхождение записи там, где читает человек. ДВЕ редакции,
#: потому что это два разных утверждения: «сделана изнутри агентской сессии»
#: и «спросить было не у чего». Одна формулировка на оба означала бы, что
#: сломанная проба ОБВИНЯЕТ человека в том, чего он не делал (оба ревьюера,
#: круг 2) — а ложная метка здесь дороже пропуска.
AGENT_SESSION_UNKNOWN_LABEL = ("происхождение не установлено: проба контура "
                               "недоступна")


def agent_session() -> str:
    """Контур, из которого делается запись; `""` — решение человека.

    Три ответа, и все три различимы: имя контура, пустая строка («переменных
    агентского контура нет», то есть человек в своём терминале — такая запись
    не помечается ничем) и `AGENT_SESSION_UNKNOWN` («спросить не у чего»).
    Значение целиком приходит из `cli_from_runtime_env()`; ни одного имени
    переменной здесь нет намеренно (один факт — один источник).

    Исключение из самой пробы тоже даёт «не определён», а не падение: эта
    функция вызывается посреди сборки записи, и traceback отсюда оставил бы
    stdout пустым — то есть ошибка представления сломала бы контракт «один
    JSON-документ» (ревьюер, круг 1).
    """
    if _cli_from_runtime_env is None:
        return AGENT_SESSION_UNKNOWN
    try:
        return one_line(_cli_from_runtime_env() or "").strip()
    except Exception:                              # noqa: BLE001 — см. выше
        return AGENT_SESSION_UNKNOWN


def agent_session_values() -> frozenset | None:
    """Допустимые значения метки, либо None, если судить не по чему.

    Множество — та же таблица, из которой метка берётся, плюс «не определён».
    Свой перечень имён разошёлся бы с ней молча: проверка начала бы отвергать
    законный контур или принимать выдуманный. None означает «источник
    недоступен» — тогда значение по составу не проверяется вовсе, потому что
    отвергать законную запись из-за сломанной установки дороже, чем пропустить
    выдуманное имя.
    """
    if _runtime_cli_names is None:
        return None
    try:
        return frozenset(_runtime_cli_names()) | {AGENT_SESSION_UNKNOWN}
    except Exception:                              # noqa: BLE001
        return None


def agent_session_origin(cli) -> str:
    """Происхождение записи ЦЕЛИКОМ, готовой фразой. Одна на оба носителя.

    Фраза целая, а не одно значение внутри чужого шаблона: шаблон
    «контур %s» с подставленным «контур не определён» давал «контур контур не
    определён» (ревьюер, круг 2), и это ровно тот случай, когда строка,
    собранная в двух местах, расходится с собой.
    """
    value = one_line(cli or "").strip()
    if value == AGENT_SESSION_UNKNOWN:
        return AGENT_SESSION_UNKNOWN_LABEL
    return "контур %s" % (value or "?")


def _stamp_session(record: dict) -> dict:
    """Поставить метку на собираемую запись — ДО контрольной суммы.

    Метку ставит сборщик записи, а не вызывающий: писатель, который забыл бы
    её поставить, выпустил бы запись, неотличимую от решения человека.
    """
    session = agent_session()
    if session:
        record[AGENT_SESSION_FIELD] = session
    return record


def _digest_fields(record: dict, base) -> tuple:
    """Набор полей суммы с учётом метки — ПОСЛЕДНИМ полем.

    Метка внутри суммы, и это ровно то, что делает её несъёмной по-тихому:
    убрать поле руками — сумма считается по базовому набору и не сходится с
    записанной; приписать его руками — тем более. Запись без метки
    подписана прежним набором байт-в-байт, поэтому законные записи, сделанные
    до появления метки, подделками не становятся (тот же приём, что у области
    действия признания).
    """
    if record.get(AGENT_SESSION_FIELD):
        return tuple(base) + (AGENT_SESSION_FIELD,)
    return tuple(base)


def agent_session_records(deferrals=None, decisions=None) -> list:
    """Помеченные записи ОБЕИХ форм — для отчёта и тела PR.

    Предмет — СОСТОЯНИЕ проекта, а не вопросы этого прогона: помеченное
    признание закрывает вопрос, и список «вопросов этого прогона» его больше
    не содержит — ровно в том прогоне, где PM обязан его увидеть.
    """
    out = []
    for form, records in (("deferral", deferrals), ("decision", decisions)):
        records = records or {}
        for key in sorted(records):
            record = records[key] or {}
            cli = record.get(AGENT_SESSION_FIELD)
            if not isinstance(cli, str) or not cli.strip():
                continue
            out.append({
                "key": key,
                "form": form,
                "form_name": _RECORD_FORM_NAMES[form],
                "cli": one_line(cli).strip(),
                # Причина и время — ЧУЖОЙ текст (их пишет argv вызывающего),
                # и нормализуются они здесь, у источника: блоков, которые их
                # печатают, двое.
                "reason": one_line(record.get("reason") or ""),
                "recordedAt": one_line(record.get("recordedAt") or ""),
            })
    return out


def agent_session_items(gate) -> list:
    """Помеченные записи из вердикта гейта. Одно чтение на всех читателей."""
    return list((gate or {}).get("agent_session_records") or [])


def agent_session_census(items) -> str:
    """`признание: 2, отсрочка: 1` — сколько и КАКИХ записей помечено.

    Счёт делает инструмент по той же замеренной причине, что и у соседних
    перечней: по списку модель считает неверно, готовую строку копирует
    дословно.
    """
    counts = {}
    for item in items or []:
        name = str(item.get("form_name") or item.get("form") or "?")
        counts[name] = counts.get(name, 0) + 1
    return ", ".join("%s: %d" % (name, counts[name]) for name in sorted(counts))


#: Заголовок блока про метку. ОДНА строка на оба носителя: отчёт для PM и
#: тело PR печатают её дословно, и расхождение двух редакций осталось бы
#: незамеченным ровно до того прогона, где важно.
AGENT_SESSION_TITLE = ("ЗАПИСИ РЕШЕНИЙ PM, СДЕЛАННЫЕ ИЗНУТРИ АГЕНТСКОЙ "
                       "СЕССИИ")

#: Заголовок ВТОРОЙ группы. Запись, у которой пробы не было, под первым
#: заголовком стала бы обвинением, которого никто не доказывал: известно
#: только, что спросить было не у чего.
AGENT_SESSION_UNKNOWN_TITLE = ("ЗАПИСИ РЕШЕНИЙ PM, ЧЬЁ ПРОИСХОЖДЕНИЕ НЕ "
                               "УСТАНОВЛЕНО")


def agent_session_groups(items) -> list:
    """`[(заголовок, записи)]` — утверждение отдельно для каждой группы.

    Две группы, а не одна с оговоркой: заголовок читают глазами, и «сделано
    изнутри агентской сессии» над записью, происхождение которой неизвестно,
    — ровно та ложная метка, которая здесь дороже пропуска. Пустая группа не
    возвращается: заголовок над пустотой это утверждение, которого никто не
    делал.
    """
    items = list(items or [])
    groups = [
        (AGENT_SESSION_TITLE,
         [i for i in items if i.get("cli") != AGENT_SESSION_UNKNOWN]),
        (AGENT_SESSION_UNKNOWN_TITLE,
         [i for i in items if i.get("cli") == AGENT_SESSION_UNKNOWN]),
    ]
    return [(title, rows) for title, rows in groups if rows]


def agent_session_lines(gate) -> list:
    """Готовый блок для PM. Пусто, когда помеченных записей нет.

    Отдельный блок, а не сноска внутри сводки: PM читает тело PR и блок
    отчёта, и факт «это решение записал не человек за терминалом, а процесс,
    начатый инструментом» обязан стоять строкой, которую нельзя пропустить
    глазами. Печатается ВСЕГДА, когда такие записи есть, — и на прогоне,
    который закончился нулём, тоже: именно он и есть тот случай, ради
    которого метка заведена.
    """
    groups = agent_session_groups(agent_session_items(gate))
    if not groups:
        return []
    lines = []
    for title, rows in groups:
        if lines:
            lines.append("")
        lines += [
            _RULE,
            "⚠ %s" % title,
            _RULE,
            "",
            "Таких записей: %d (%s)." % (len(rows), agent_session_census(rows)),
        ]
        for i, item in enumerate(rows, 1):
            lines.append("%d. [%s] %s, %s (записано %s)"
                         % (i, item.get("key") or "—",
                            item.get("form_name") or "?",
                            agent_session_origin(item.get("cli")),
                            item.get("recordedAt") or "?"))
            if item.get("reason"):
                lines.append("   %s" % item["reason"])
    lines += ["", "Чего эта метка НЕ значит:"]
    lines += ["- %s" % limit for limit in AGENT_SESSION_LIMITS]
    lines += ["", _RULE]
    return lines


def agent_session_pr_lines(items) -> list:
    """Тот же факт в markdown — раздел тела PR. Пусто, когда метки нет.

    ОДИН рендер на двух вызывающих: тело PR прогона собирает его из вердикта
    гейта, а команда записи дописывает его сразу после самой записи. Две
    редакции этого раздела разошлись бы молча, и в одном из двух носителей
    объявленная граница оказалась бы короче (оба ревьюера, круг 1: путь
    дописывания печатал метку хвостом строки и границы не нёс вовсе).
    """
    groups = agent_session_groups(items)
    if not groups:
        return []
    out = []
    for title, rows in groups:
        if out:
            out.append("")
        out.append("**%s (%d: %s)**"
                   % (title, len(rows), agent_session_census(rows)))
        # Происхождение и причина — чужой текст; кодовый спан с ограждением по
        # содержимому не даёт им сбежать в разметку.
        out += ["- `%s` — %s, %s: %s (записано %s)"
                % (i.get("key") or "?", i.get("form_name") or "?",
                   md_code(agent_session_origin(i.get("cli"))),
                   md_code(i.get("reason") or ""),
                   i.get("recordedAt") or "?")
                for i in rows]
    out += ["", "Чего эта метка НЕ значит:"]
    out += ["- %s" % limit for limit in AGENT_SESSION_LIMITS]
    return out


# ── записи отсрочек ────────────────────────────────────────────────────────

def deferral_digest(record: dict) -> str:
    """Контрольная сумма полей записи. См. «честную границу» в docstring."""
    parts = [_DIGEST_DOMAIN]
    parts += [one_line(record.get(f) or "")
              for f in _digest_fields(record, _DIGEST_FIELDS)]
    return hashlib.sha256("\x00".join(parts).encode("utf-8")).hexdigest()


def make_deferral(key: str, reason: str, recorded_at: str,
                  question: dict | None = None) -> dict:
    """Собрать запись отсрочки (с контрольной суммой и меткой контура)."""
    record = _stamp_session({
        "key": one_line(key).strip(),
        "reason": one_line(reason).strip(),
        "recordedAt": one_line(recorded_at).strip(),
    })
    if question:
        # Справочные поля: они НЕ участвуют в контрольной сумме и ни на что не
        # влияют — их задача показать человеку в дифф-е состояния, что именно
        # было отложено. Включи их в сумму — и правка опечатки в адресе
        # превратила бы законную запись в «сделанную мимо команды».
        for field in ("kind", "id", "path"):
            if question.get(field):
                record[field] = one_line(question[field])
    record["digest"] = deferral_digest(record)
    return record


def read_deferrals(state) -> tuple:
    """`(валидные по ключу, отвергнутые записи)` из состояния проекта.

    Отвергнутая запись — НЕ тишина: она возвращается отдельным списком и
    печатается в отчёте. Молча проигнорированная подделка неотличима от её
    отсутствия, а разница как раз в том, что кто-то её писал.
    """
    return _read_records(state, PM_DEFERRALS_FIELD, deferral_digest)


def _read_records(state, field, digest_of) -> tuple:
    """Разбор списка записей решения PM. Одна форма — один разбор."""
    valid: dict = {}
    rejected: list = []
    if not isinstance(state, dict):
        return valid, rejected
    raw = state.get(field)
    if raw is None:
        return valid, rejected
    if not isinstance(raw, list):
        rejected.append({
            "key": None,
            "detail": "поле `%s` должно быть списком, а пришло `%s`"
                      % (field, type(raw).__name__),
        })
        return valid, rejected
    for item in raw:
        if not isinstance(item, dict):
            rejected.append({"key": None,
                             "detail": "запись не объект (`%s`)"
                                       % type(item).__name__})
            continue
        key = item.get("key")
        reason = item.get("reason")
        if not isinstance(key, str) or not KEY_RE.match(key.strip()):
            rejected.append({"key": key if isinstance(key, str) else None,
                             "detail": "ключ не имеет формы `<класс>:<8 hex>`"})
            continue
        if not isinstance(reason, str) or not reason.strip():
            rejected.append({"key": key,
                             "detail": "причина пуста — отсрочка без причины "
                                       "не записывается"})
            continue
        # Время записи — обязательное поле формы, а не украшение: по нему PM
        # читает, КОГДА решение принято, и оно же входит в контрольную сумму.
        # Запись без него проходила проверку суммы (сумма считалась от пустой
        # строки) и закрывала вопрос, печатаясь как «записано ?» — форма,
        # которой документированный контракт не знает (ревьюер, круг 1).
        recorded_at = item.get("recordedAt")
        if not _valid_timestamp(recorded_at):
            rejected.append({"key": key,
                             "detail": "время записи не имеет формы "
                                       "`YYYY-MM-DDTHH:MM:SSZ` — форма записи "
                                       "нарушена, отсрочка не засчитывается"})
            continue
        # Метка контура необязательна (её нет у решения человека), но если
        # она есть — она обязана быть непустой строкой. Пустая строка и
        # `false` тут особенно дороги: сумма считается по базовому набору
        # полей, то есть такая запись выглядела бы и законной, и
        # непомеченной одновременно.
        mark = item.get(AGENT_SESSION_FIELD, _MARK_ABSENT)
        if mark is not _MARK_ABSENT and (not isinstance(mark, str)
                                         or not mark.strip()):
            rejected.append({
                "key": key,
                "detail": "метка агентской сессии имеет форму `%s`, а не имя "
                          "контура — форма записи нарушена, запись не "
                          "засчитывается"
                          % ("пустая строка" if isinstance(mark, str)
                             else type(mark).__name__),
            })
            continue
        # Имя контура проверяется по СОСТАВУ, а не только по форме: метку
        # можно приписать руками, пересчитав сумму, и тогда в отчёт PM
        # уезжало бы любое слово — хоть «человек» (ревьюер, круг 1).
        # Множество читается у того же источника, из которого метка берётся;
        # когда источник недоступен, состав не проверяется вовсе — отвергать
        # законную запись из-за сломанной установки дороже.
        known = agent_session_values()
        # Сравнивается ИСХОДНОЕ значение, а не приведённое: сборщик записи
        # кладёт имя уже нормализованным, поэтому у законной записи разницы
        # нет, а у подделанной она есть — `"gigacode\n"` с пересчитанной
        # суммой прошёл бы сверку по приведённому виду, оставшись в состоянии
        # значением, которого в таблице контуров нет (ревьюер, круг 2).
        if mark is not _MARK_ABSENT and known is not None \
                and mark not in known:
            rejected.append({
                "key": key,
                "detail": "метка агентской сессии называет контур `%s`, "
                          "которого нет среди известных (%s) — запись не "
                          "засчитывается"
                          % (one_line(mark).strip(), ", ".join(sorted(known))),
            })
            continue
        expected = digest_of(item)
        if item.get("digest") != expected:
            rejected.append({
                "key": key,
                "detail": "контрольная сумма записи не сходится — запись "
                          "сделана мимо команды `polisade_pm_defer.py`; "
                          "гейт её не засчитывает",
            })
            continue
        valid[key.strip()] = item
    return valid, rejected


# ── подтверждения решений ──────────────────────────────────────────────────
#
# Форма записи та же, что у отсрочки, а домен контрольной суммы — другой:
# иначе отсрочку можно было бы переложить в подтверждения переносом байтов,
# и «отложено» стало бы «решено» без единой новой подписи.
_DECISION_DOMAIN = "polisade-pm-decision-v1"

#: Поля подтверждения, входящие в контрольную сумму. ШИРЕ, чем у отсрочки, на
#: адрес артефакта и слепок его полей исхода: у отсрочки справочные поля
#: намеренно вне суммы (правка опечатки в адресе не должна делать законную
#: запись «сделанной мимо команды»), а здесь эти два поля не справочные — ими
#: определяется, КАКОЙ исход признан. Оставить их снаружи значило бы отдать
#: область действия признания на правку руками: переписать `outcomeAddress` в
#: соседний артефакт можно было бы, не тронув сумму.
_DECISION_DIGEST_FIELDS = _DIGEST_FIELDS + ("outcomeAddress", "outcomeSubject")


def decision_digest(record: dict) -> str:
    """Контрольная сумма подтверждения. Домен свой — см. комментарий выше.

    Набор полей зависит от того, ЕСТЬ ли у записи область действия. Запись без
    неё подписана тем же набором, что и до появления исходов: иначе обновление
    плагина превратило бы все уже записанные законные признания в подделки, и
    решение, которое человек однажды назвал, предъявлялось бы ему как чужое
    (оба ревьюера, круг 1). Ослабления здесь нет: запись без области действия
    ничего на барьере исходов и не закрывает — закрывает ПАРА «адрес и
    слепок», а её в такой записи нет.
    """
    fields = _DIGEST_FIELDS
    if record.get("outcomeAddress") or record.get("outcomeSubject"):
        fields = _DECISION_DIGEST_FIELDS
    parts = [_DECISION_DOMAIN]
    parts += [one_line(record.get(f) or "")
              for f in _digest_fields(record, fields)]
    return hashlib.sha256("\x00".join(parts).encode("utf-8")).hexdigest()


def make_decision(key: str, reason: str, recorded_at: str,
                  outcome: dict | None = None) -> dict:
    """Собрать запись подтверждения решения (с контрольной суммой).

    `outcome` — область действия признания по исходу артефакта:
    `{"address": …, "subject": …}`. Её вычисляет :func:`outcome_scope` из
    журнала гейта и диска, а не вызывающий: адрес и слепок обязаны быть
    ровно теми, что барьер потом сверит, и второе их вычисление разошлось бы
    молча.
    """
    record = _stamp_session({
        "key": one_line(key).strip(),
        "reason": one_line(reason).strip(),
        "recordedAt": one_line(recorded_at).strip(),
    })
    if outcome:
        record["outcomeAddress"] = one_line(outcome.get("address") or "").strip()
        record["outcomeSubject"] = one_line(outcome.get("subject") or "").strip()
    record["digest"] = decision_digest(record)
    return record


def read_decisions(state) -> tuple:
    """`(валидные по ключу, отвергнутые)` подтверждения из состояния проекта.

    Проверки ровно те же, что у отсрочек, и специально ОДНОЙ функцией: два
    разбора одной формы разошлись бы молча, и подтверждение начало бы
    засчитываться там, где отсрочка уже нет.
    """
    return _read_records(state, PM_DECISIONS_FIELD, decision_digest)


