def question_reference(root, key) -> dict:
    """Адрес вопроса по ключу из ЖУРНАЛА гейта: `{kind, id, path}` либо пусто.

    Единственный источник этих полей. Вычислять их второй раз в команде
    отсрочки значило бы завести второе написание адреса, а пустая запись без
    адреса — это обещание видимости, которого форма не выполняет.
    """
    entries, _rejected, _err = read_ledger(root)
    for entry in entries or []:
        if str(entry.get("key") or "") != str(key or ""):
            continue
        return {f: entry.get(f) for f in ("kind", "id", "path")
                if entry.get(f)}
    return {}


def _with_disk_status(root, entry) -> dict:
    """Запись со статусом предмета; если в ней его нет — прочитанным с диска.

    Поле `status` появилось у записей позже самих записей, и журнал, написанный
    прежней версией, его не несёт. Опереться только на поле значило бы молчать
    ровно на том проекте, который уже посреди инцидента: запись есть, статус
    в артефакте есть, а отказ не срабатывает. Дозаполнение при сверке этот
    случай закрывает лишь тогда, когда гейт успел прогнуться ПОСЛЕ обновления;
    здесь же предмет читается напрямую — адрес у записи уже есть.

    Молчание при нечитаемом артефакте сознательно: «файл не прочитан» и «это не
    исход» — разные ответы, но отказать по первому значило бы запретить
    законную отсрочку из-за чужой поломки.
    """
    if entry.get("status") is not None:
        return entry
    if str(entry.get("kind") or "") not in _STATUS_SUBJECT_KINDS:
        return entry
    target = _safe_target(root, entry.get("path"))
    if not target:
        return entry
    try:
        with open(target, encoding="utf-8", errors="replace") as handle:
            front = parse_frontmatter(handle.read(), strip_comments=True)
    except (OSError, ValueError):
        return entry
    return dict(entry, status=one_line(str(front.get("status") or "")))


def deferral_refusal(root, key) -> str:
    """Почему отсрочка по этому ключу не годится, либо пусто.

    Читает ЖУРНАЛ гейта: только там известно, про какой предмет был задан
    вопрос с этим ключом. Команда отсрочки сама гейт не считает, а угадывать
    класс по человекочитаемой части ключа мало — битая форма исхода приезжает
    под ключом соседнего класса.

    Молчит, когда записи нет: «журнала не было» и «вопрос не про исход» —
    разные ответы, и отказывать по первому значило бы запрещать отсрочку на
    проекте, где гейт ещё не запускался.
    """
    entries, _rejected, _err = read_ledger(root)
    for entry in entries or []:
        if str(entry.get("key") or "") != str(key or ""):
            continue
        entry = _with_disk_status(root, entry)
        if outcome_like(entry):
            return (
                "Ключ `%s` назван вопросом про статус, но в артефакте лежит "
                "исход `%s` — отмена, неактуальность или неприменимость. Это "
                "РЕШЕНИЕ человека, и отсрочкой оно не закрывается: «разберусь "
                "позже» здесь значит «решение уже принято, а кем — потом», то "
                "есть ровно то, что барьер останавливает. Вопрос приехал "
                "соседним классом потому, что исход записан неверной формой "
                "(пустая причина, `not_actual` не у BUG). Путей два: "
                "исправить форму записи статуса — тогда вопрос задастся как "
                "исход и его можно ПРИЗНАТЬ командой с `%s`; либо поставить "
                "артефакту статус, соответствующий действительности."
                % (one_line(str(key)), one_line(str(entry.get("status") or "")),
                   CONFIRM_OPT))
    return ""


def defer_script_path() -> str:
    """Абсолютный путь к ЕДИНСТВЕННОМУ писателю отсрочек — рядом с нами."""
    return os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "polisade_pm_defer.py")


def _interpreter() -> str:
    return sys.executable or "python3"


#: Опция, которой та же команда записывает ПОДТВЕРЖДЕНИЕ решения, а не
#: отсрочку. Имя живёт здесь, потому что читают его двое: команда, которая
#: его разбирает, и гейт, который печатает готовую строку вызова.
CONFIRM_OPT = "--confirm"


def defer_command_factory(project_root, pr_body_path=None, argv=None):
    """Фабрика готовой команды отсрочки для конкретного ключа."""
    def _build(key: str) -> str:
        parts = [_interpreter(), defer_script_path(), str(project_root),
                 "--key=%s" % key, "--reason=<причина одной строкой>"]
        if pr_body_path:
            parts.append("--pr-body=%s" % pr_body_path)
        return " ".join(shlex.quote(p) for p in parts)
    return _build


def confirm_command_factory(project_root, pr_body_path=None):
    """Фабрика готовой команды подтверждения решения для конкретного ключа."""
    def _build(key: str) -> str:
        parts = [_interpreter(), defer_script_path(), str(project_root),
                 CONFIRM_OPT, "--key=%s" % key,
                 "--reason=<кто принял решение и почему, одной строкой>"]
        if pr_body_path:
            parts.append("--pr-body=%s" % pr_body_path)
        return " ".join(shlex.quote(p) for p in parts)
    return _build


#: Опции, которые повторная ПРОВЕРКА не повторяет: они пишут — либо (как
#: объявление шага внутри цикла) относятся к прогону, которого уже не будет.
_WRITING_OPTS = ("--apply", "--yes", INTERMEDIATE_OPT)
_WRITING_OPT_PREFIXES = ("--pr-body=", "--enable=", "--disable=",
                         "--adopt-templates", "--adopt-v2-defaults")
#: Те же опции в форме «имя и значение двумя словами». Снимается ПАРА:
#: имя без своего значения оставляет значение позиционным аргументом.
_VALUE_OPTS = ("--pr-body", "--enable", "--disable", "--adopt-templates")


def recheck_command(argv=None) -> str:
    """Та же команда без записи — ею проверяется, что условие исчезло.

    Строится из ЖИВОГО argv, а не из представления рецепта о нём: корень
    проекта и диагностические опции (например `--migrate-design`, от которого
    зависит часть вопросов) обязаны остаться, иначе повторная проверка
    ответила бы про другой набор вопросов.
    """
    argv = list(sys.argv if argv is None else argv)
    script = os.path.abspath(argv[0]) if argv and argv[0] else ""
    rest = []
    skip_next = False
    for token in argv[1:]:
        if skip_next:
            # Значение, отданное ОТДЕЛЬНЫМ словом. Белого списка имён мало без
            # арности: `--pr-body /путь` терял только имя, путь оставался, и
            # «та же команда без записи» переписывала уже собранное тело PR
            # отчётом dry-run (ревьюер, круг 1). Сверка принимает обе формы,
            # значит обе формы обязаны и сниматься.
            skip_next = False
            continue
        if token in _WRITING_OPTS:
            continue
        if token in _VALUE_OPTS:
            skip_next = True
            continue
        if any(token.startswith(p) for p in _WRITING_OPT_PREFIXES):
            continue
        rest.append(token)
    parts = [_interpreter()] + ([script] if script else []) + rest
    return " ".join(shlex.quote(p) for p in parts)
