#: Форма ключа: `<класс>:<12 hex>`. Класс — для человека в командной строке,
#: хеш — для машины. Проверяется при записи отсрочки, чтобы «отложить всё
#: сразу» не выражалось одним токеном. Двенадцать, а не восемь: восемь это 32
#: бита, и на проекте в тысячу вопросов пара совпадений перестаёт быть
#: небылицей, а цена совпадения — молча закрытый чужой отсрочкой вопрос
#: (ревьюер, круг 1).
KEY_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,39}:[0-9a-f]{12}$")

#: Управляющие символы в однострочном значении. Та же причина, что и у
#: `_polisade_pr_body.one_line`: причина отсрочки печатается PM'у и в тело PR,
#: и перевод строки разорвал бы пункт списка на два.
_CONTROL_RE = re.compile(r"[\x00-\x1f\x7f-\x9f]")

#: Форма времени записи — та же, что печатает `_polisade_state_io.utc_timestamp`.
RECORDED_AT_FORMAT = "%Y-%m-%dT%H:%M:%SZ"


def _valid_timestamp(value) -> bool:
    """Время записи — существующий момент в документированной форме.

    Регулярка по цифрам закрыла бы только «вчера»: `2026-99-99T99:99:99Z`
    состоит из цифр и прошло бы её (ревьюер, круг 2). Разбор календарём
    закрывает класс целиком и не заводит второго написания формы.
    """
    if not isinstance(value, str):
        return False
    try:
        datetime.datetime.strptime(value, RECORDED_AT_FORMAT)
    except ValueError:
        return False
    return True

_RULE = "═" * 62


def one_line(value: Any) -> str:
    """Значение как ОДНА строка (управляющие символы → пробел)."""
    return _CONTROL_RE.sub(" ", str(value))


def _address(value):
    """Адрес артефакта ОДНОЙ строкой, с сохранением «поля не было».

    `None` проходит насквозь: «поля не было» и «поле пустое» — разные
    машинные ответы, и схлопывать их в один значило бы стереть различие,
    которое потребитель отчёта вправе читать (ревьюер, круг 2). Нормализация
    стоит здесь, у источника, а не в трёх печатающих блоках: правило,
    записанное трижды, расходится молча.
    """
    return None if value is None else one_line(value)


def md_code(value) -> str:
    """Значение как КОДОВЫЙ СПАН markdown, что бы в нём ни лежало.

    Имя файла на POSIX может содержать обратную кавычку, и спан из одной
    кавычки она закрывает досрочно: остаток адреса уезжает в разметку тела PR
    (ревьюер, круг 2). Длина ограждения выбирается по содержимому — так
    предписывает сам формат, — а пробелы-подушки нужны, когда значение
    начинается или кончается кавычкой.
    """
    text = one_line(value)
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    fence = "`" * (longest + 1)
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return "%s%s%s%s%s" % (fence, pad, text, pad, fence)


def _slug(text: str) -> str:
    out = re.sub(r"[^a-z0-9]+", "-", str(text).lower()).strip("-")
    return (out[:40].strip("-") or "question")


#: Поля, которые в предмет вопроса НЕ входят: это его ФОРМУЛИРОВКА и то, что
#: добавляет к вопросу сам гейт. Всё остальное — предмет.
#:
#: Запрет, а не разрешение, и это разница между экземпляром и классом
#: (ревьюер, круг 2): белый список закрывал ровно те поля, которые были
#: названы, и следующий класс вопроса, различающийся, скажем, по
#: `status_reason` или `expected`, снова получил бы один ключ на два разных
#: решения. Формулировка исключена намеренно: переписанный при обновлении
#: плагина текст не имеет права молча снять отсрочку.
_KEY_PROSE_FIELDS = frozenset({
    "kind",            # идёт в ключ отдельно, человекочитаемой частью
    "question", "detail",
    "defer_command",   # добавляет гейт, а не производитель вопроса
})


def question_key(question: dict) -> str:
    """Устойчивый ключ вопроса — `<класс>:<8 hex>`.

    Ключуется ПРЕДМЕТ вопроса: класс (`kind`), адрес, которым его называет сам
    инструмент (`id`, `path`, `silo` — последний адресует вопрос про пакет, у
    остальных он пуст), и машинные поля, которыми вопрос ОТЛИЧАЕТСЯ от
    соседнего про тот же артефакт (`status`, `reason`). Последние два
    добавлены по находке ревью: отложить «у TASK-001 неизвестный статус X» и
    получить молчание про «у TASK-001 теперь сломан status_reason» — разные
    решения, а ключ был один. Пустые поля в ключ не вносят ничего, поэтому у
    классов, которые их не заполняют, ключ не изменился по смыслу.

    Формулировка в ключ НЕ входит: отсрочка это решение про предмет, и
    переписанный при обновлении плагина текст вопроса не имеет права молча
    снять её. Обратная сторона названа честно:
    если вопрос про ТОТ ЖЕ предмет сменит смысл, старая отсрочка продолжит его
    закрывать — поэтому смена смысла обязана идти вместе со сменой `kind`.

    Хеш, а не склейка полей: идентификатор бывает путём с двоеточием и
    пробелами, а ключ едет в командную строку.
    """
    kind = str(question.get("kind") or "question")
    # Значение сериализуется, а не приводится к строке: `0`, `False`, `"0"` и
    # `None` — четыре разных машинных ответа, и `str(... or "")` склеивал их
    # в один (ревьюер, круг 2). Ключи сортируются: порядок полей в чужом
    # словаре не наш контракт.
    subject = "\x00".join(
        "%s=%s" % (field, json.dumps(question.get(field), sort_keys=True,
                                     ensure_ascii=False, default=str))
        for field in sorted(set(question) - _KEY_PROSE_FIELDS))
    digest = hashlib.sha256(
        ("%s\x00%s" % (kind, subject)).encode("utf-8")).hexdigest()[:12]
    return "%s:%s" % (_slug(kind), digest)


