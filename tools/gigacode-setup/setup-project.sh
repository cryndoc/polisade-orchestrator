#!/usr/bin/env bash
# Polisade Orchestrator — установка рантайм-скриптов в проект (GigaCode).
#
# Зачем это отдельный шаг. Под GigaCode защита файловой системы не даёт
# исполнять скрипты из каталога установки расширения, поэтому они живут в
# самом проекте — в `.polisade/bin`. Скопировать их может только человек:
# команда, в аргументах которой назван защищённый каталог, отклоняется до
# запуска, и это же мешает агенту сделать перенос за вас (issue #127).
#
# Запуск — из КОРНЯ вашего проекта, одной строкой:
#
#     bash ~/.gigacode/extensions/polisade/setup-project.sh
#
# Скрипт идемпотентен: та же строка годится и для первой установки, и после
# каждого обновления плагина. Ничего не делает молча — при любом расхождении
# возвращает ненулевой код и печатает, что именно не сошлось (issue #297).
#
# ⚠️ Скрипт удаляет каталог (`rm -rf .polisade/bin`), поэтому всё, что может
# увести это удаление в сторону, проверяется ДО него и приводит к отказу:
# каждый компонент пути назначения обязан быть настоящим каталогом внутри
# проекта и на той же файловой системе, что корень, а манифест — разобраться
# целиком и строго. Ни одна проверка не опирается на то, что путь «выглядит
# правильно».
#
# ГРАНИЦА, названная явно. Проверки идут ДО удаления, и между ними остаётся
# окно: тот, кто в этот момент может писать в каталог проекта, способен
# подменить компонент пути ссылкой уже после проверки. Закрыть это в языке
# оболочки нечем — нужны операции относительно открытого дескриптора каталога
# с семантикой no-follow. Модель угроз здесь другая: скрипт защищает от ОШИБКИ
# (не тот каталог, забытый шаг, испорченный архив), а не от того, у кого уже
# есть право записи в ваш репозиторий — такой человек и без него правит
# `.polisade/bin`, то есть код, который плагин затем исполняет.

set -u

MANIFEST_NAME="MANIFEST.sha256"
DEST_REL=".polisade/bin"
PARENT_REL=".polisade"

die() { printf 'ОШИБКА: %s\n' "$1" >&2; exit "${2:-1}"; }
note() { printf '%s\n' "$1"; }

# ── откуда берём файлы ────────────────────────────────────────────────────
# Путь считается от расположения САМОГО скрипта, а не от аргумента: подстановка
# пути руками — один из трёх отказов, ради которых скрипт и написан.
script_path="${BASH_SOURCE[0]:-$0}"
# ── где мы находимся ──────────────────────────────────────────────────────
# Возвращает значение С МЕТКОЙ `x` на конце — её снимает вызывающий. Без метки
# всю работу отменяла бы ВНЕШНЯЯ подстановка команд на стороне вызова: она
# срезает завершающие переводы строк ровно так же, как та, от которой мы
# защищаемся (поймано собственным прогоном — соседний файл всё ещё удалялся).
capture() {
    local out
    out="$("$@" && printf x)" || return 1
    out="${out%x}"
    printf '%sx' "${out%$'\n'}"
}

# Каталог берётся РАСКРЫТИЕМ ПАРАМЕТРА, а не `$(dirname …)`: подстановка команд
# срезала бы завершающий перевод строки в имени каталога, и метка на `pwd -P`
# этого не спасала — обрезка происходила раньше, ещё на пути к `cd`. Поймано
# собственным прогоном: скрипт брал `scripts/` СОСЕДНЕГО каталога.
case "$script_path" in
    */*) script_parent="${script_path%/*}" ;;
    *)   script_parent="." ;;
esac
script_dir="$(cd -- "$script_parent" > /dev/null 2>&1 && capture pwd -P)" \
    || die "не удалось определить каталог скрипта"
script_dir="${script_dir%x}"
src_dir="$script_dir/scripts"
src_manifest="$src_dir/$MANIFEST_NAME"

[ -d "$src_dir" ] || die "рядом со скриптом нет каталога scripts/ ($src_dir).
Похоже, скрипт вынут из архива расширения — запускай его на месте:
  bash ~/.gigacode/extensions/polisade/setup-project.sh"
[ -f "$src_manifest" ] || die "в $src_dir нет $MANIFEST_NAME — это не сборка
GigaCode. Переустанови расширение из архива polisade-gigacode.zip."

for tool in git find mktemp; do
    command -v "$tool" > /dev/null 2>&1 \
        || die "не найден $tool — без него проверить копию нечем. Ничего не создано."
done

# Подстановка команд СРЕЗАЕТ завершающие переводы строк, поэтому корень с именем
# `foo<LF>` сравнялся бы с соседним `foo`, и удаление ушло бы в чужой проект
# (замерено: соседний файл был удалён). Sentinel-байт сохраняет имя дословно, а
# снимается ровно один протокольный перевод строки.
# `GIT_DIR`/`GIT_WORK_TREE`/`GIT_COMMON_DIR` из окружения позволяют выдать ЛЮБОЙ
# каталог за корень чужого репозитория — замерено: `rm -rf` удалил файлы в
# каталоге, который репозиторием не является. Обычные worktree и подмодули git
# найдёт сам по своему `.git`; переменные здесь не нужны никому.
unset GIT_DIR GIT_WORK_TREE GIT_COMMON_DIR GIT_INDEX_FILE

git_root="$(capture git rev-parse --show-toplevel 2> /dev/null)" \
    || die "текущий каталог не внутри git-репозитория:
  $(pwd)
Перейди в корень своего репозитория и запусти строку оттуда. Ничего не создано."

git_root="${git_root%x}"

here="$(capture pwd -P)" || die "не удалось определить текущий каталог"
here="${here%x}"
git_root_phys="$(cd -- "$git_root" > /dev/null 2>&1 && capture pwd -P)" \
    || die "не удалось разрешить корень репозитория: $git_root"
git_root_phys="${git_root_phys%x}"

[ "$here" = "$git_root_phys" ] || die "запуск не из корня проекта:
  сейчас:  $here
  корень:  $git_root_phys
Перейди в корень и повтори. Ничего не создано."

project_root="$git_root_phys"

# Копировать расширение в самоё себя нельзя: получится каталог внутри каталога,
# а следующий запуск снёс бы исходники.
case "$project_root/" in
    "$script_dir"/*) die "запуск изнутри каталога установки расширения:
  $project_root
Перейди в корень своего проекта. Ничего не создано." ;;
esac

# ── каждый компонент назначения обязан быть настоящим каталогом ───────────
# Без этого `rm -rf project/.polisade/bin` при `.polisade -> /том/с/данными`
# удалял бы `/том/с/данными/bin`: ядро разыменовывает промежуточную ссылку, и
# ни кавычки, ни `--` от этого не защищают (находка ревью, P0).
if [ -L "$project_root/$PARENT_REL" ]; then
    die "$PARENT_REL в этом проекте — символическая ссылка.
Удалять и переписывать каталог по ссылке скрипт не станет: это запись за
пределы проекта. Разберись с ней вручную. Ничего не создано."
fi
if [ -e "$project_root/$PARENT_REL" ] && [ ! -d "$project_root/$PARENT_REL" ]; then
    die "$PARENT_REL существует, но это не каталог. Ничего не создано."
fi
mkdir -p -- "$project_root/$PARENT_REL" || die "не удалось создать $PARENT_REL"

parent_phys="$(cd -- "$project_root/$PARENT_REL" > /dev/null 2>&1 && capture pwd -P)" \
    || die "не удалось разрешить $PARENT_REL"
parent_phys="${parent_phys%x}"
[ "$parent_phys" = "$project_root/$PARENT_REL" ] || die "$PARENT_REL ведёт за
пределы проекта:
  ожидалось: $project_root/$PARENT_REL
  на деле:   $parent_phys
Ничего не создано."

# Точка монтирования — не ссылка, `pwd -P` её не раскрывает, и все проверки
# выше она проходит: `.polisade`, смонтированный на чужой том, отдал бы этому
# `rm -rf` содержимое того тома (находка ревью, оба круга). Сравниваем номер
# устройства с корнем проекта. Если `stat` в системе другой — говорим, что
# проверка НЕ сделана, и продолжаем: молчаливый пропуск здесь хуже отказа, а
# ложный отказ на каждой системе без `stat` хуже обоих.
# GNU-форма проверяется ПЕРВОЙ: на GNU `stat -f` тоже завершается успешно, но
# печатает не номер устройства, поэтому «первая успешная команда» молча брала
# бы неверное число (находка ревью).
if stat -c '%d' -- "$project_root" > /dev/null 2>&1; then
    dev_of() { stat -c '%d' -- "$1" 2> /dev/null; }
elif stat -f '%d' -- "$project_root" > /dev/null 2>&1; then
    dev_of() { stat -f '%d' -- "$1" 2> /dev/null; }
else
    dev_of() { :; }
fi
root_dev="$(dev_of "$project_root")"
check_same_device() {
    local what="$1" path="$2" dev
    [ -n "$root_dev" ] || return 0
    dev="$(dev_of "$path")"
    [ -n "$dev" ] || return 0
    [ "$dev" = "$root_dev" ] || die "$what лежит на другой файловой системе
(точка монтирования?), чем корень проекта. Удалять и переписывать там скрипт не
станет. Ничего не создано."
}
if [ -z "$root_dev" ]; then
    note "ПРЕДУПРЕЖДЕНИЕ: не нашёл подходящий stat — проверка на точку"
    note "монтирования не выполнена; остальные проверки в силе."
fi
check_same_device "$PARENT_REL" "$parent_phys"

if [ -L "$project_root/$DEST_REL" ]; then
    die "$DEST_REL — символическая ссылка. Скрипт не станет её ни удалять, ни
переписывать: это чужая осознанная настройка, и запись пошла бы за пределы
проекта. Ничего не создано."
fi
if [ -e "$project_root/$DEST_REL" ] && [ ! -d "$project_root/$DEST_REL" ]; then
    die "$DEST_REL существует, но это не каталог. Ничего не создано."
fi

dest_dir="$parent_phys/bin"

# 🚨 Проверяется именно то, что будет УДАЛЕНО. Проверка одного `.polisade`
# пропускала отдельную файловую систему, смонтированную прямо в
# `.polisade/bin`: все прочие проверки она проходит, и `rm -rf` снёс бы её
# содержимое без всякой гонки (находка ревью круга 3, оба ревьюера).
if [ -e "$dest_dir" ]; then
    check_same_device "$DEST_REL" "$dest_dir"
fi

# ── чем считаем контрольные суммы ─────────────────────────────────────────
if command -v sha256sum > /dev/null 2>&1; then
    sha_of() { sha256sum -- "$1" | cut -d' ' -f1; }
elif command -v shasum > /dev/null 2>&1; then
    sha_of() { shasum -a 256 -- "$1" | cut -d' ' -f1; }
elif command -v openssl > /dev/null 2>&1; then
    sha_of() { openssl dgst -sha256 -- "$1" | awk '{print $NF}'; }
else
    die "не нашёл ни sha256sum, ни shasum, ни openssl — нечем сверить копию.
Ничего не создано: копировать без возможности проверить смысла нет."
fi

# ── СТРОГИЙ разбор манифеста — ДО любого удаления ─────────────────────────
# Разбор fail-closed, как и у `/polisade:doctor`: манифест, который не разобрался
# целиком, — это повреждённая поставка, и продолжать по ней значит сверять копию
# с тем, что от манифеста уцелело. Плохая строка, дубль, `..`, абсолютный путь
# или чужой формат отвергают ВЕСЬ прогон, пока ничего ещё не удалено.
tmp_names="$(mktemp)" || die "не удалось создать временный файл"
tmp_rows="$(mktemp)" || die "не удалось создать временный файл"
tmp_found=""
cleanup() { rm -f -- "$tmp_names" "$tmp_rows" ${tmp_found:+"$tmp_found"}; }
trap cleanup EXIT

# Заголовки — РОВНО по одному и ровно в ожидаемой форме. Проверка «есть такая
# строка» проходила на манифесте с пустой версией и с двумя `# target:`, из
# которых один чужой, — то есть на подделке, которую `/polisade:doctor` отвергает
# (находка ревью). Установщик обязан читать манифест не мягче доктора.
[ -L "$src_manifest" ] && die "$MANIFEST_NAME — символическая ссылка. Манифест,
который указывает наружу, не является описанием этой поставки. Ничего не создано."
ver_lines="$(grep -c '^# plugin-version: ' "$src_manifest" || true)"
[ "$ver_lines" = "1" ] || die "в $MANIFEST_NAME должно быть РОВНО одно
'# plugin-version:', найдено $ver_lines — поставка повреждена."
# Версия — РОВНО один непробельный токен до конца строки. Проверка «начинается
# с непробела» принимала `# plugin-version: 3.7.11 forged`, который
# `/polisade:doctor` отвергает как искажённый заголовок: установщик сказал бы
# «Совпало всё», а доктор следом забраковал бы копию (находка ревью).
grep -qE '^# plugin-version: [^[:space:]]+$' "$src_manifest" \
    || die "в $MANIFEST_NAME заголовок версии пуст или искажён — поставка
повреждена."
tgt_lines="$(grep -c '^# target: ' "$src_manifest" || true)"
[ "$tgt_lines" = "1" ] || die "в $MANIFEST_NAME должно быть РОВНО одно
'# target:', найдено $tgt_lines — поставка повреждена."
grep -q '^# target: gigacode$' "$src_manifest" \
    || die "$MANIFEST_NAME не помечен '# target: gigacode' — это манифест другой
сборки. Переустанови расширение из архива polisade-gigacode.zip."

lineno=0
while IFS= read -r line || [ -n "$line" ]; do
    lineno=$((lineno + 1))
    case "$line" in
        '#'*|'') continue ;;
    esac
    digest="${line%%  *}"
    rel="${line#*  }"
    case "$digest" in
        *[!0-9a-f]*|'') die "строка $lineno манифеста: контрольная сумма не
шестнадцатеричная. Поставка повреждена, ничего не создано." ;;
    esac
    [ "${#digest}" -eq 64 ] || die "строка $lineno манифеста: длина контрольной
суммы не 64. Поставка повреждена, ничего не создано."
    [ -n "$rel" ] && [ "$rel" != "$line" ] || die "строка $lineno манифеста: нет
имени файла после суммы. Поставка повреждена, ничего не создано."
    case "$rel" in
        /*|*/../*|../*|*/..|..|*'\'*) die "строка $lineno манифеста: имя '$rel'
выходит за пределы каталога или содержит обратный слэш (его `/polisade:doctor`
нормализует и отвергает). Поставка повреждена, ничего не создано." ;;
        *' '*) : ;;   # пробел в имени допустим, проверяется как есть
    esac
    if grep -Fxq -- "$rel" "$tmp_names" 2> /dev/null; then
        die "строка $lineno манифеста: имя '$rel' встречается дважды. Поставка
повреждена, ничего не создано."
    fi
    printf '%s\n' "$rel" >> "$tmp_names"
    printf '%s\t%s\n' "$digest" "$rel" >> "$tmp_rows"
done < "$src_manifest"

[ -s "$tmp_names" ] || die "манифест $MANIFEST_NAME не содержит ни одной записи —
сборка расширения повреждена. Ничего не создано."

# ── снос прежней копии и перенос ──────────────────────────────────────────
# `rm -rf` здесь не косметика: POSIX `cp -R src dst` при существующем dst кладёт
# копию ВНУТРЬ, и получается `.polisade/bin/scripts/*.py` — сверка падает, а
# причина неочевидна. Путь собран из РАЗРЕШЁННОГО физического корня и констант.
if [ -e "$dest_dir" ]; then
    rm -rf -- "$dest_dir" || die "не удалось снести прежний $DEST_REL"
fi
mkdir -p -- "$dest_dir" || die "не удалось создать $DEST_REL"

# Копируем СОДЕРЖИМОЕ (`/.`), а не каталог: так вложенный `bin/scripts`
# невозможен по построению, а не по внимательности.
cp -R -- "$src_dir/." "$dest_dir/" || die "не удалось скопировать файлы в $DEST_REL"

# ── сверка ────────────────────────────────────────────────────────────────
manifest="$dest_dir/$MANIFEST_NAME"
[ -L "$manifest" ] && die "после копирования $MANIFEST_NAME оказался
символической ссылкой — копия недостоверна."
[ -f "$manifest" ] || die "после копирования $MANIFEST_NAME отсутствует."
plugin_version="$(sed -n 's/^# plugin-version: //p' "$manifest" | head -1)"
[ -n "$plugin_version" ] || plugin_version="(в манифесте не указана)"

checked=0
missing=""
mismatched=""
while IFS="$(printf '\t')" read -r expected rel; do
    [ -n "$rel" ] || continue
    if [ ! -f "$dest_dir/$rel" ] || [ -L "$dest_dir/$rel" ]; then
        missing="$missing  $rel
"
        continue
    fi
    actual="$(sha_of "$dest_dir/$rel")"
    if [ "$actual" != "$expected" ]; then
        mismatched="$mismatched  $rel
"
    fi
    checked=$((checked + 1))
done < "$tmp_rows"

# Лишние файлы — тоже расхождение: так ловится остаток прежней копии, который не
# удалился, и вложенный `bin/scripts` от переноса руками. Сравнение ТОЧНОЕ
# (`grep -Fxq`), а не по регулярному выражению: файл с именем `.*` иначе совпал
# бы с любой записью манифеста и проехал (находка ревью). Ссылки перечисляются
# наравне с файлами — манифест их не хеширует, а `/polisade:doctor` копию со
# ссылкой бракует. Ничего не исключается: каталог только что создан нами, и
# всё, чего нет в манифесте, туда попасть не могло.
# Список берётся ЧЕРЕЗ ФАЙЛ с проверкой кода возврата: у подстановки команд
# он теряется, и `find`, упавший по любой причине, дал бы пустой список — то
# есть «лишних нет» и зелёный исход на непроверенной копии.
tmp_found="$(mktemp)" || die "не удалось создать временный файл"
# `-print0` и чтение по NUL: имя файла может содержать перевод строки, и
# построчное чтение разорвало бы его на два несуществующих «лишних» файла.
find "$dest_dir" \( -type f -o -type l \) -print0 > "$tmp_found" \
    || die "не удалось перечислить файлы в $DEST_REL — копия не проверена."

extra=""
while IFS= read -r -d '' found; do
    [ -n "$found" ] || continue
    rel="${found#"$dest_dir"/}"
    [ "$rel" = "$MANIFEST_NAME" ] && continue
    if ! grep -Fxq -- "$rel" "$tmp_names"; then
        extra="$extra  $rel
"
    fi
done < "$tmp_found"

# ── исход ─────────────────────────────────────────────────────────────────
note "Polisade Orchestrator — рантайм-скрипты установлены в проект."
note "  версия плагина: $plugin_version"
note "  каталог:        $DEST_REL"
note "  сверено файлов: $checked"

problems=0
if [ -n "$missing" ]; then
    printf 'НЕ СКОПИРОВАНЫ или не являются обычными файлами:\n%s' "$missing" >&2
    problems=1
fi
if [ -n "$mismatched" ]; then
    printf 'НЕ СОВПАЛИ по контрольной сумме:\n%s' "$mismatched" >&2
    problems=1
fi
if [ -n "$extra" ]; then
    printf 'ЛИШНИЕ файлы (нет в манифесте):\n%s' "$extra" >&2
    problems=1
fi

if [ "$problems" -ne 0 ]; then
